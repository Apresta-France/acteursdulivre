<p>En additionnant les postes indispensables — correction, maquette, couverture simple, impression — le budget le plus fréquent se situe entre <strong>3 400 et 5 800 €</strong>. Ajoutez 1 200 à 2 400 € si une préparation de copie est nécessaire. Ajoutez encore la diffusion, les exemplaires presse et les frais de salon : ce n’est plus de la fabrication, mais cela sort du même compte.</p>
<p>Les auteurs qui étalent ces postes sur deux trimestres obtiennent en moyenne des devis plus bas, simplement parce qu’ils laissent aux métiers le choix du créneau. Un « pour vendredi » se paie. Un brief incomplet aussi : le prestataire protège sa marge contre les allers-retours.</p>
<p>ISBN : en France, l’AFNIL attribue des listes aux éditeurs déclarés ; un autoédité qui n’est pas éditeur passe souvent par un intermédiaire (quelques dizaines d’euros). Le dépôt légal auprès de la BnF est gratuit, mais il faut envoyer les exemplaires. Prévoyez 80 à 200 € pour ces à-côtés, pas zéro.</p>

<h2>Comment faire baisser le coût sans casser le livre ?</h2>
<p>Pas le rabais de dernière minute. Trois leviers reviennent chez les prestataires.</p>
<ol>
  <li><strong>Un brief clair</strong> — nombre de signes, délai, fichiers déjà prêts, ce qui est inclus (épreuves, fichiers d’impression, déclinaisons de couverture).</li>
  <li><strong>Du temps</strong> — un créneau à trois semaines coûte moins cher qu’un rendu express. Les <a href="/prestataires">prestataires</a> remplissent d’abord les plannings stables.</li>
  <li><strong>Un poste à la fois</strong> — correction, puis maquette, puis impression. Les forfaits « je m’occupe de tout » diluent les responsabilités et rendent les devis incomparables.</li>
</ol>
<p>Ce qu’il ne faut pas couper en premier : la correction et la maquette. Un roman fauté dans une belle impression reste un roman fauté. Un roman propre mal mis en pages a l’air d’un dossier. L’illustration, le pelliculage, le grammage : là, on peut arbitrer.</p>
