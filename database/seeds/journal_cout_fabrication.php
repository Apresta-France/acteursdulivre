<h2>Comment comparer deux devis de fabrication ?</h2>
<p>Ramenez-les à la même unité et à la même liste de livrables. Un devis « moins cher » qui oublie les épreuves n’est pas moins cher.</p>
<ul>
  <li>Même volume (signes ou pages), même délai, même nombre de passes.</li>
  <li>Fichiers rendus : Word annoté, PDF épreuves, PDF/X imprimeur, sources InDesign ou non.</li>
  <li>Cession de droits pour la couverture : durée, territoire, supports.</li>
  <li>Impression : papier nommé (pas « bouffant » tout court), pelliculage, dos, port.</li>
  <li>Ce qui est hors champ : index, notes, images intérieures, version e-pub.</li>
</ul>
<p>Si deux devis restent incomparables, c’est souvent que l’un vend une correction et l’autre une préparation de copie. Relisez les intitulés. Puis posez la question par écrit. Le suivi à jalons d’<a href="/a-propos">Acteurs du Livre</a> sert précisément à figer ce périmètre avant le règlement hors site.</p>

<h2>Questions fréquentes</h2>
<h3>Combien coûte l’autoédition d’un roman en France en 2026 ?</h3>
<p>Pour un roman de 300 pages tiré à 300 exemplaires, comptez 3 400 à 5 800 € de fabrication (correction, maquette, couverture, impression), hors diffusion. Un livre uniquement numérique revient beaucoup moins cher, mais ce n’est plus le même objet ni le même circuit.</p>
<h3>Faut-il corriger avant de faire la maquette ?</h3>
<p>Oui. Corriger après maquette coûte plus cher : chaque correction déplace les fins de ligne et les pages. L’ordre utile est : texte stabilisé, correction (et éventuellement préparation de copie), puis maquette, puis épreuves, puis impression.</p>
<h3>L’impression à la demande suffit-elle pour un premier roman ?</h3>
<p>Elle suffit pour tester, offrir, envoyer quelques services de presse. Dès que vous visez des salons ou un dépôt en librairie, un tirage court chez un imprimeur livre est en général plus cohérent — papier, dos, coût à l’exemplaire.</p>
<h3>Qui paie la commission sur Acteurs du Livre ?</h3>
<p>Le prestataire. Aucun abonnement. La première mission réalisée est offerte ; ensuite 8 % sont facturés au prestataire lorsque le client confirme et note. Le prix de la mission se règle hors plateforme. Détail sur la page <a href="/tarifs">Tarifs</a>.</p>
<h3>Peut-on faire fabriquer un livre sans ISBN ?</h3>
<p>Oui, pour un usage privé. Dès que vous vendez ou déposez en librairie, l’ISBN devient le sésame pratique. Le dépôt légal reste obligatoire pour tout livre mis en circulation en France.</p>
<h3>L’IA générative peut-elle remplacer la correction ou la couverture ?</h3>
<p>Pas sur Acteurs du Livre : aucun livrable texte, image ou voix ne peut être produit par une IA générative. Ailleurs, une passe automatique n’est pas une correction professionnelle, et une image générée pose des questions de droits et de ressemblance. Les métiers restent des métiers.</p>

