<p>Un graphiste qui « fait aussi la couverture » n’est pas forcément <a href="/metiers/maquette">maquettiste livre</a>. Demandez des références imprimées, pas seulement des PDF écran. Vérifiez les fonds perdus, le dos calculé sur le grammage réel, et la livraison des fichiers d’impression (PDF/X, aplats, profils).</p>
<p>Une couverture typographique soignée peut rester sous 400 €. Une <a href="/metiers/illustration">illustration originale</a>, cession limitée au livre, se situe plutôt entre 300 et 900 €. Au-delà, vous achetez souvent une exclusivité large, des déclinaisons (bandeau, quatrième, réseaux) ou un illustrateur déjà identifié.</p>
<p>Cinq lignes à exiger par écrit : durée, territoires, supports (papier, numérique, audio), exclusivité, et ce qui se passe en cas de réédition. Sans elles, vous ne savez pas ce que vous avez acheté.</p>

