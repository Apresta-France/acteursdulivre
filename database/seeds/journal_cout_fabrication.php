<h2>Qu’est-ce que la fabrication d’un livre ?</h2>
<p>La <strong>fabrication d’un livre</strong> désigne l’ensemble des opérations qui transforment un manuscrit validé en objet imprimable, puis imprimé : correction, mise en pages, fichiers d’impression, choix du papier, tirage et façonnage. Elle commence après l’écriture. Elle s’arrête avant la diffusion en librairie.</p>
