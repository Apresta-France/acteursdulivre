<h2>Correction et préparation de copie : quel budget ?</h2>
<p>Sur 520 000 signes, une <strong>correction orthotypographique</strong> complète se situe en général entre 620 et 1 100 €. L’écart s’explique moins par la réputation du correcteur que par l’état du texte : un manuscrit déjà relu, ou passé par une préparation de copie, coûte souvent un tiers moins cher à corriger.</p>
<p>La <em>préparation de copie</em> est autre chose. Elle retravaille la cohérence, les répétitions, le rythme, parfois le plan. Comptez plutôt 1 200 à 2 400 €. Ce n’est pas « une correction plus chère » : c’est un autre métier. Les confondre, c’est soit sous-payer un préparateur, soit acheter trop cher une simple chasse aux fautes.</p>
<p>Demandez toujours : nombre de signes (et comment ils sont comptés), nombre de passes, relecture sur épreuves incluse ou non, et le format du fichier rendu. Un devis au feuillet de 1 500 signes n’est pas comparable à un devis à la page Word. Les <a href="/metiers/correction">correcteurs de l’annuaire</a> précisent en principe l’unité.</p>
