<h2>Pourquoi la placer avant la correction ?</h2>
<p>Parce que corriger un texte que vous allez encore déplacer est une dépense à fonds perdu. La chaîne utile : écriture que vous assumez, bêta-lecture, réécriture, éventuellement préparation de copie, puis correction, puis <a href="/metiers/maquette">maquette</a>.</p>
<p>Sur un roman de 300 pages, la correction ortho seule se situe entre 620 et 1 100 €. Si la bêta vous conduit à couper trente pages et à refondre deux arcs, ces 620 € auraient été payés deux fois. La bêta à 180-450 € est, dans ce cas, le poste le moins cher de la chaîne — à condition d’en tirer des décisions, pas seulement un compliment.</p>
<p>Le budget fabrication d’un roman autoédité (correction, maquette, couverture, impression) se situe souvent entre 3 400 et 5 800 € hors diffusion. Voir <a href="/journal/cout-fabrication-roman-autoedition">Combien coûte la fabrication d’un roman en autoédition ?</a>.</p>

<h2>Que doit contenir le brief ?</h2>
<p>Le genre, le public visé, le stade du texte (premier jet, troisième version), ce que vous savez déjà faible, ce que vous ne voulez pas rouvrir. Un auteur qui dit « soyez impitoyable sur le rythme, mais ne touchez pas à la voix » aide le prestataire. Un auteur qui dit « dites-moi ce que vous en pensez » recevra un avis, pas un outil de travail.</p>
<p>Joignez le décompte de signes et, si possible, une question de lecture : « Le dénouement est-il préparé ? », « La narratrice est-elle crédible après le chapitre 8 ? ». Plus la question est précise, plus le rapport est actionnable.</p>

<h2>Comment choisir un bêta-lecteur ?</h2>
<p>Par le genre qu’il lit vraiment, pas par la proximité. Un lecteur de polar n’est pas interchangeable avec un lecteur de fantasy. Demandez des extraits de rapports (anonymisés), pas seulement des éloges d’auteurs. Vérifiez le délai : une bêta « en dix jours » sur 500 000 signes n’est pas une lecture, c’est un survol.</p>
