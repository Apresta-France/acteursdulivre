<h2>Qu’est-ce qu’un rapport de bêta-lecture ?</h2>
<p>Le bêta-lecteur lit comme un lecteur exigeant, puis rend compte. Le rapport dit où le livre accroche, où il lâche, où un personnage disparaît, où le rythme s’essouffle, où une intrigue secondaire noie la principale. Il argumente. Il cite des passages. Il ne réécrit pas le chapitre à votre place.</p>
<p>Un bon livrable tient souvent en huit à quinze pages, plus éventuellement un fichier annoté. Il distingue les avis de goût (« j’aurais préféré ») des constats de fonctionnement (« au chapitre 14, le mobile n’est plus tenable »). C’est cette distinction que vous payez.</p>
<p>La <a href="/metiers/beta-lecture">bêta-lecture</a> professionnelle n’est pas un club de lecture. Elle a un brief, un délai, un prix. Sur <a href="/">acteursdulivre.fr</a>, c’est une mission comme une autre, avec un périmètre figé avant le règlement hors plateforme.</p>

<h2>Ce que le bêta-lecteur ne corrige pas</h2>
<p>L’orthographe, la typographie, le code des dialogues. S’il signale une faute, c’est en passant. S’il passe son temps à les chasser, il n’est plus en train de lire le roman : il est en train de faire le métier d’à côté, mal, et trop tôt.</p>
<p>Il ne tranche pas non plus « est-ce publiable en maison ». Cette question relève de la <a href="/metiers/lecture-editoriale">lecture éditoriale</a> ou d’un <a href="/metiers/agent-litteraire">agent littéraire</a>. Le bêta-lecteur dit si <em>ce</em> livre, pour <em>ce</em> lecteur, tient la route. L’éditeur dit s’il peut le défendre dans un catalogue.</p>
<blockquote>
  <p>« Un rapport de bêta-lecture sert à décider quoi réécrire. Une correction sert à ne plus avoir honte des épreuves. »</p>
