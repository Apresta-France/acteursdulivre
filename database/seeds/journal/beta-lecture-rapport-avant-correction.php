<h2>Combien de lecteurs faut-il ?</h2>
<p>Un bon rapport vaut mieux que trois avis contradictoires sans méthode. Deux bêta-lecteurs de profils différents (par exemple un lecteur de genre et un lecteur « généraliste ») peuvent éclairer un angle mort. Au-delà, vous collectionnez des opinions : vous n’achetez plus une prestation, vous fuyez la décision.</p>
<p>Les retours de <a href="/metiers/librairie">libraires</a> ou les échanges en salon sont précieux plus tard, une fois le livre fabriqué. Ils ne remplacent pas une lecture de manuscrit.</p>

<h2>Comment travailler le rapport sans se perdre ?</h2>
<p>Lisez-le une première fois sans corriger. Laissez passer quarante-huit heures. Classez ensuite les remarques : je retiens / je discute / je laisse. Réécrivez par couches (structure, puis scènes, puis phrases). Puis seulement, envoyez vers la prépa ou la correction.</p>
<p>Sur la plateforme, pas d’abonnement : la première mission du prestataire est offerte, puis 8 % lui sont facturés ; vous réglez la mission hors site. Voir <a href="/comment-ca-marche">comment ça marche</a> et les <a href="/tarifs">tarifs</a>. Les <a href="/prestations">prestations</a> packagées et l’<a href="/inscription">inscription</a> gratuite permettent de lancer une recherche sans engagement. Aucune bêta-lecture ne peut être produite par une IA générative : page <a href="/confiance">Confiance</a>.</p>

<h2>Questions fréquentes</h2>
<h3>La bêta-lecture est-elle utile en autoédition ?</h3>
<p>Oui, surtout si vous n’avez pas de comité. C’est souvent le seul regard structuré avant d’engager 3 400 à 5 800 € de fabrication. Elle ne garantit pas les ventes ; elle évite d’imprimer un roman que vous auriez encore dû rouvrir.</p>
<h3>Peut-on bêta-lire un essai ou une BD ?</h3>
<p>Oui, à condition que le prestataire lise ce format. Pour un essai, le rapport porte sur l’argumentation et la clarté. Pour une BD, il faut souvent coordonner avec le scénario et les planches — un autre brief, un autre tarif.</p>
<h3>Le bêta-lecteur doit-il rester anonyme vis-à-vis des maisons ?</h3>
<p>Ce n’est pas une règle. En revanche, le manuscrit reste le vôtre. Un prestataire sérieux ne le circule pas. Les usages de confidentialité se figent dans la mission ; le volet <a href="/metiers/juridique">juridique</a> peut aider si le texte est sensible.</p>
<h3>Faut-il payer un ami qui lit bien ?</h3>
<p>Si vous en faites une mission avec délai et livrable, oui — et autant passer par un cadre clair. Si c’est un service entre proches, ce n’est pas une prestation : n’en attendez pas un rapport professionnel.</p>
<h3>L’IA peut-elle remplacer une bêta-lecture ?</h3>
<p>Pas sur Acteurs du Livre, et pas comme équivalent. Un résumé automatique n’a pas lu votre livre comme un lecteur de genre. Les manuscrits ne servent pas à entraîner un modèle.</p>

