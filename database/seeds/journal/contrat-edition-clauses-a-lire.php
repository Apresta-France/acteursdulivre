<p>Les taux « classiques » de roman (autour de 8 à 12 % grand format, moins en poche, autre clé en numérique) restent des ordres de grandeur : chaque maison a sa grille. L’important n’est pas de mémoriser un pourcentage, c’est de savoir <em>sur quelle assiette</em> il s’applique (prix public HT, recettes nettes, ventes nettes de retours).</p>
<p>La reddition doit permettre de recouper : exemplaires vendus, retournés, offerts, prix moyen. Sans cela, le taux est décoratif. Un <a href="/metiers/agent-litteraire">agent</a> lit ces lignes pour métier ; un juriste, pour la validité. Ce n’est pas le même devis.</p>

<h2>Exploitation, délai de parution, corrections</h2>
<p>L’éditeur a une obligation d’exploitation permanente et suivie. Le contrat fixe souvent un délai de parution (par exemple 12 à 24 mois). Au-delà, une clause de résiliation ou de retour des droits doit exister — sinon le manuscrit dort. Vérifiez qui décide du titre définitif, de la couverture, du texte après <a href="/metiers/correction">correction</a> : un droit de regard n’est pas un droit de veto, selon la rédaction.</p>
<p>Méfiez-vous de la clause qui met les corrections d’auteur « au-delà d’un certain pourcentage » à votre charge, surtout si le seuil est bas. Une passe de corrections normales sur épreuves n’est pas une réécriture. Distinguez aussi la préparation de copie interne de ce que l’on vous facturerait en extra.</p>
