<h2>Sortie de catalogue et retour des droits</h2>
<p>Un livre peut être « disponible » en impression à la demande tout en étant invisible : pas de réimpression soignée, pas de diffusion, pas de page à jour. La clause de <strong>sortie de catalogue</strong> définit quand l’exploitation est réputée cessée (seuil de ventes, rupture de stock non réassortie, retrait de l’offre numérique) et dans quel délai les droits reviennent. Sans elle, vous négociez des années plus tard avec une maison qui n’existe plus sous le même nom.</p>
<p>Prévoyez le sort des fichiers (intérieur, couverture) : les récupérez-vous pour une réédition ailleurs ? L’<a href="/metiers/illustration">illustrateur</a> de couverture a souvent cédé à l’éditeur, pas à vous : le retour de vos droits d’auteur sur le texte n’emporte pas automatiquement l’image.</p>
<ol>
  <li><strong>Seuil</strong> — nombre d’exemplaires ou chiffre d’affaires en dessous duquel l’exploitation est jugée arrêtée.</li>
  <li><strong>Délai</strong> — mois après mise en demeure pour réassortir ou rendre les droits.</li>
  <li><strong>Supports</strong> — papier et numérique traités ensemble ou séparément.</li>
  <li><strong>Fichiers</strong> — qui les détient, pour quel usage après retour.</li>
</ol>

<h2>Options, exclusivités, ce qu’on ne signe pas les yeux fermés</h2>
<p>L’option sur le « prochain ouvrage du même genre » peut bloquer un an ou deux. C’est négociable : durée courte, genre circonscrit, réponse écrite sous un délai. Une exclusivité trop large empêche un autre éditeur, une revue, parfois une prépublication.</p>
<p>Les contrats de compte d’auteur (vous payez l’édition) ne sont pas des contrats d’édition au sens habituel : relisez l’objet. Si vous payez la fabrication, vous n’êtes pas dans le même équilibre ; les clauses de cession doivent être encore plus étroites. Un prestataire d’<a href="/a-propos">Acteurs du Livre</a> qui fabrique un livre n’est pas votre éditeur pour autant.</p>
