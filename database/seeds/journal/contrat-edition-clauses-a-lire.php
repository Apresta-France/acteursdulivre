<h2>Ce que cède un contrat d’édition</h2>
<p>En droit français, l’auteur cède des <em>droits patrimoniaux</em> (reproduction, représentation) pour une exploitation. Le droit moral (paternité, respect de l’œuvre) ne se cède pas. Le contrat d’<a href="/metiers/edition">édition</a> dit <em>quels</em> droits, <em>où</em>, <em>combien de temps</em>, sur <em>quels supports</em>. « Tous droits, tous formats, monde entier, durée légale » est une phrase courte et très large : livre, numérique, audio, adaptations, parfois merchandising si on ne borne pas.</p>
<p>Demandez la ventilation. Papier grand format et poche n’ont pas le même taux. Le numérique et l’<a href="/metiers/audio">audio</a> sont souvent des cessions distinctes, ou des alinéas séparés. La <a href="/metiers/traduction">traduction</a> peut rester à l’auteur ou passer par l’éditeur. Une cession « y compris les adaptations audiovisuelles » n’est pas anodine : c’est un autre marché.</p>
<p>Sur <a href="/">acteursdulivre.fr</a>, personne ne signe à votre place. Vous pouvez commander une <a href="/prestations">prestation</a> de relecture de contrat. Voir <a href="/comment-ca-marche">comment ça marche</a>.</p>

<h2>À-valoir, taux, reddition</h2>
<p>L’à-valoir (acompte) se situe, pour beaucoup de premiers romans, entre zéro et quelques milliers d’euros — parfois rien, parfois un montant symbolique. Il s’impute : vous ne touchez des droits d’auteur qu’une fois l’à-valoir « remboursé » par les ventes. Un à-valoir élevé avec un taux bas et une reddition annuelle tardive peut rapporter moins qu’un à-valoir nul avec un taux clair et un relevé semestriel.</p>
