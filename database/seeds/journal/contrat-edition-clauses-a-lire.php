<h2>Questions fréquentes</h2>
<h3>Peut-on négocier un premier contrat ?</h3>
<p>Souvent sur la durée, le territoire, l’audio, l’option, les délais de reddition — moins sur le taux d’un premier roman à faible à-valoir. Demander par écrit une modification n’est pas une insulte. Un refus motivé vaut mieux qu’un « c’est le standard » sans montrer la clause.</p>
<h3>L’à-valoir est-il définitivement acquis ?</h3>
<p>En principe oui s’il est versé et que le contrat n’en fait pas un prêt. Vérifiez les cas de résiliation avant parution : certains contrats prévoient une restitution. D’où l’intérêt de la date de versement.</p>
<h3>Que faire si la reddition n’arrive pas ?</h3>
<p>Relance écrite, puis mise en demeure selon le contrat et le Code de la propriété intellectuelle. Un juriste ou un agent cadre l’étape. Ne publiez pas le litige sur les réseaux à la place.</p>
<h3>Faut-il un agent pour signer ?</h3>
<p>Pas une obligation. Utile dès que la cession dépasse le livre papier France, ou que plusieurs maisons sont en jeu. L’agent se rémunère sur les droits ; le juriste, à l’heure ou au forfait. Ce n’est pas interchangeable.</p>
<h3>Un contrat numérique seul est-il un contrat d’édition ?</h3>
<p>Oui s’il cède des droits d’exploitation contre une obligation d’éditer. Lisez-le avec les mêmes quatre blocs. Une plateforme de diffusion qui prend une licence non exclusive n’est pas toujours un éditeur : le vocabulaire du document prime sur le marketing.</p>

