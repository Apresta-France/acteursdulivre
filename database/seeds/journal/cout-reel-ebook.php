<h2>Questions fréquentes</h2>
<h3>Pourquoi un e-book n’est-il pas gratuit à produire ?</h3>
<p>Parce que le travail est dans le texte et le fichier, pas dans la rame de papier. Correction, conversion, couverture et identifiants restent dus. L’impression, elle, peut attendre — ou n’arriver jamais.</p>
<h3>Puis-je corriger moi-même et ne payer que la conversion ?</h3>
<p>Oui, si le texte est réellement stable. Comptez alors surtout 250 à 700 € de conversion et 200 à 600 € de couverture simple. Une relecture sur épreuves reste recommandée : on ne voit pas les mêmes fautes à l’écran de travail et sur liseuse.</p>
<h3>Faut-il un ISBN pour un e-book ?</h3>
<p>Pas toujours pour exister sur une unique boutique en ligne. Oui, dès que vous voulez un identifiant portable, des librairies multiples, des bibliothèques, un suivi propre. Un ISBN papier ne couvre pas le fichier numérique.</p>
<h3>EPUB ou PDF pour vendre ?</h3>
<p>EPUB pour la vente liseuse et la plupart des librairies. PDF pour un document figé (beau livre, partition, certains essais très composés) ou pour un SP. Les deux ne s’improvisent pas l’un pour l’autre.</p>
<h3>Le numérique remplace-t-il le broché ?</h3>
<p>Pour certains lecteurs, oui. Pour les <a href="/metiers/librairie">librairies</a> physiques, les dédicaces et beaucoup de salons, non. Beaucoup d’auteurs font les deux : correction unique, déclinaisons de fabrication. Le budget papier s’ajoute alors — ce n’est plus le sujet de cet article.</p>

