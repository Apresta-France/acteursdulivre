<p>En 2026, publier un roman en e-book « propre » — texte corrigé, fichier EPUB contrôlé, couverture simple, ISBN numérique — coûte en général <strong>entre 1 200 et 2 800 €</strong>, <em>hors impression</em>. Le fichier n’est pas gratuit parce qu’il n’y a pas de papier : les métiers restent. Ce qui disparaît, c’est le tirage, le façonnage et une partie du stockage. Pas la langue, pas la mise en pages, pas l’identifiant.</p>
