<h2>Diffusion : boutiques, librairies, audio</h2>
<p>Le fichier ne se vend pas tout seul. Les agrégateurs et librairies numériques prennent une commission sur chaque vente — ce n’est pas un coût de fabrication, c’est une marge de distribution. Comparez : exclusivité d’une boutique contre présence en librairies en ligne multiples. Le choix change le prix public net, pas le coût de l’EPUB.</p>
<p>La fiche (résumé, mots-clés, catégorie, âge) est un travail éditorial court. Mal faite, elle enterre un bon fichier. Elle n’exige pas une agence. Elle exige d’avoir lu trois fiches de titres comparables.</p>
<p>Le livre <a href="/metiers/audio">audio</a> est un autre budget (narration humaine, prises, mastering). Une synthèse vocale n’est pas une prestation acceptable ici. Ne rangez pas l’audio dans « le numérique » : ce n’est pas le même métier, ni le même contrat de droits.</p>

