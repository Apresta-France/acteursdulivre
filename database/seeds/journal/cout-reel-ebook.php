<h2>Un e-book n’est pas un PDF exporté</h2>
<p>Un <strong>livre numérique</strong> commercial, en France, circule surtout en EPUB (parfois en formats de librairies). Le texte s’adapte à la liseuse : corps, marges, police choisie par le lecteur. Un PDF figé peut servir d’épreuve ou de service de presse ; ce n’est pas le même produit que l’EPUB vendu.</p>
<p>La conversion professionnelle part d’un fichier propre (Word ou InDesign stabilisé) et produit un EPUB contrôlé : métadonnées, table des matières, césures, italiques, notes, intertitres, images éventuelles. Un <a href="/metiers/maquette">maquettiste</a> livre qui « fait aussi le numérique » n’est pas forcément un convertisseur ; un convertisseur n’est pas forcément un typographe papier. Demandez le livrable : EPUB 3, contrôles (ePubCheck ou équivalent), et une passe sur liseuse réelle.</p>
<p>Ce que l’on voit encore trop : des files d’erreurs de styles (vingt styles de paragraphe pour le même corps), des images à 72 dpi utilisées en pleine page, des notes converties en simple astérisque. La conversion révèle le désordre du fichier source. D’où l’ordre utile : texte stabilisé, <a href="/metiers/correction">correction</a>, puis fabrication numérique.</p>

<h2>La correction : le poste qu’on ne saute pas</h2>
<p>Sur un roman de 450 000 à 550 000 signes, une correction orthotypographique complète se situe souvent entre <strong>620 et 1 100 €</strong> — les mêmes ordres de grandeur que pour le papier, parce que le travail est le même. L’e-book fauté se partage plus vite que le broché fauté. Ce n’est pas le lieu de « se rattraper plus tard ».</p>
<p>La préparation de copie (structure, répétitions, rythme) est un autre métier, souvent 1 200 à 2 400 €. Elle n’est pas obligatoire pour tout premier roman. Elle l’est dès que le texte n’est pas encore un livre. La confondre avec « une correction un peu plus chère » fausse tous les devis.</p>
<p>Corriger <em>après</em> conversion coûte plus cher : chaque correction de fond peut casser la table des matières, les ancres, les notes. L’ordre reste : texte, correction, puis EPUB, puis relecture sur épreuves numériques (une passe courte, à prévoir au devis).</p>

<h2>Couverture numérique, ISBN, dépôt</h2>
<p>La couverture e-book est une image de <strong>première plat seule</strong> — pas de dos, pas de quatrième, sauf si vous les déclinez pour le site. Un visuel simple (typographie soignée, ou illustration déjà cédée pour le numérique) peut rester dans le lot 1 200–2 800 €. Une <a href="/metiers/illustration">illustration originale</a> s’ajoute souvent de 300 à 900 €, avec une cession qui cite explicitement le livre numérique et les librairies en ligne.</p>
<p>L’ISBN du fichier numérique n’est pas celui du broché. En France, l’AFNIL attribue des listes aux éditeurs déclarés ; un autoédité passe souvent par un intermédiaire (quelques dizaines d’euros). Publier « sans ISBN » sur une seule boutique en ligne est possible techniquement ; cela complique librairies, bibliothèques et suivi. Le dépôt légal des documents numériques auprès de la BnF a ses propres modalités : ce n’est pas zéro minute.</p>
<p>Prévoyez 40 à 150 € pour identifiants et à-côtés, pas une ligne fantôme. Une <a href="/metiers/edition">prestation d’édition</a> peut les inclure ; alors exigez la liste, pour ne pas les payer deux fois.</p>

