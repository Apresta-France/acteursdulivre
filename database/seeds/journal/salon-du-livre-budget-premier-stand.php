<h2>Questions fréquentes</h2>
<h3>Un premier salon est-il rentable ?</h3>
<p>Rarement si l’on additionne table, route et coût des livres. Il est utile s’il produit des contacts (libraire, presse, lecteurs qui laissent un avis) et une expérience de vente en face-à-face. Jugez-le sur ces deux points, pas sur le seul chiffre du dimanche soir.</p>
<h3>Faut-il un kakemono ?</h3>
<p>Non pour une première table. Une pile bien dressée, une affiche lisible à deux mètres et vous debout font plus que un roll-up trop large pour le stand.</p>
<h3>Peut-on partager une table ?</h3>
<p>Souvent oui, si le règlement l’autorise. Cela divise le droit de table et oblige à se relayer. Accordez-vous sur le stock, la caisse et les horaires avant d’arriver.</p>
<h3>Combien de livres vendre pour « réussir » ?</h3>
<p>Il n’y a pas de seuil officiel. Dix à vingt ventes sur un week-end local, pour un titre inconnu, est déjà une journée vivante. Zéro vente avec des échanges utiles n’est pas un scandale ; zéro vente et zéro parole, si.</p>
<h3>Les grands salons nationaux sont-ils un bon premier choix ?</h3>
<p>Presque jamais : coût, fatigue, concurrence, règles d’accès. Commencez par un salon de bassin de vie, puis montez si le livre a une demande.</p>

