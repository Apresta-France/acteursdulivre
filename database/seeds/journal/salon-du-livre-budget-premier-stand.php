<h2>Quel stock emporter ?</h2>
<p>Trente exemplaires pour une journée locale, soixante à quatre-vingts pour un week-end un peu passant : c’est déjà ambitieux pour un titre inconnu. Mieux vaut racheter ou se faire livrer que rentrer avec une caisse de dos cornés. Les livres qui voyagent mal (pelliculage fragile, grand format lourd) se dégradent dans le coffre.</p>
<p>Calculez le prix public et votre seuil : si l’exemplaire vous revient à 6 € et que vous vendez à 18 €, chaque vente aide, mais le droit de table et l’essence se mangent les premières unités. Un premier salon qui « rembourse la table » est déjà un bon résultat. Compter dessus pour écouler le tirage est un autre métier — celui du dépôt en <a href="/metiers/librairie">librairie</a> et du service de presse.</p>
