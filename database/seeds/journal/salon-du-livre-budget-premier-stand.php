<h2>L’animation : ce qui n’est pas optionnel</h2>
<p>Rester assis derrière une pile n’est pas une présence. Les organisateurs attendent que vous soyez là aux heures d’ouverture, que vous parliez aux visiteurs sans les agresser, que vous teniez le créneau de rencontre s’il est au programme. Une lecture de huit minutes, une dédicace à heure dite, un échange avec le libraire partenaire du salon : c’est de l’<em>animation</em>, pas du décor.</p>
<p>Préparez trois phrases à voix haute : de quoi parle le livre, pour qui, pourquoi vous êtes à <em>ce</em> salon. Pas le résumé de quatrième intégral. Ayez de la monnaie, un stylo, et la date du prochain rendez-vous (dépôt, autre salon, parution d’une suite) si elle existe.</p>
<p>La <a href="/metiers/presse-com">presse locale</a> se prévient dix à quinze jours avant, avec l’horaire de la rencontre. Un communiqué d’une page suffit. Ce n’est pas un service de presse national : c’est une info agenda.</p>

<h2>Choisir le premier salon — et savoir dire non</h2>
<p>Un salon de proximité, avec un public qui lit déjà votre genre, vaut mieux qu’une grande halle où vous êtes perdu entre des éditeurs installés. Demandez le nombre d’exposants, la gratuité ou non pour le public, la présence d’une librairie partenaire, la communication (affiche, radio locale). Méfiez-vous des manifestations qui vivent de l’inscription des auteurs plus que des visiteurs.</p>
<ol>
  <li><strong>Distance</strong> — aller-retour dans la journée si possible, pour le premier.</li>
  <li><strong>Ligne</strong> — jeunesse, BD, poésie, roman : le salon affiche-t-il la vôtre ?</li>
  <li><strong>Règlement</strong> — table partagée ou non, vente autorisée, commission éventuelle de l’organisateur.</li>
  <li><strong>Calendrier</strong> — pas la semaine de votre réimpression, pas le même week-end qu’un dépôt important.</li>
  <li><strong>Coût total</strong> — table + route + nuits, pas la table seule.</li>
</ol>
