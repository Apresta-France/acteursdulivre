<h2>Premier roman, petite maison, autoédition</h2>
<p>Un premier roman sans angle (sujet, territoire, actualité, lectorat identifiable) se défend mal en un mois. L’AP honnête le dit, et propose soit un cadrage plus long, soit un travail d’angle avant les envois. Payer 2 000 € pour 80 colis silencieux n’est pas « le marché qui a parlé » : c’est un brief trop tardif.</p>
<p>Les petites maisons ont souvent un AP à temps partagé. L’auteur autoédité achète le même métier, sans le logo d’éditeur. Le fichier ne s’ouvre pas plus vite pour autant — parfois moins. D’où l’intérêt des relais locaux : presse régionale, librairies, <a href="/metiers/salons">salons</a>, associations. Moins glamour, plus réel.</p>
<p>La <a href="/">place de marché</a> permet de comparer des profils livre, pas des agences généralistes qui « font aussi la culture ». L’<a href="/inscription">inscription</a> est gratuite ; le brief doit citer la date de parution, le genre, le territoire, et le stock disponible pour le SP.</p>

<h2>Comment briefer et mesurer</h2>
<p>Cinq informations suffisent à un devis comparable : date de parution (ou de disponibilité), genre et accroche en cinq lignes, cibles (nationale / régionale / spécialisée), nombre d’exemplaires déjà prévus, et ce qui est déjà en place (site, newsletter, dates libraires).</p>
<p>Mesurez ensuite ce qui était promis : nombre d’envois, nombre de relances, pièces publiées, invitations obtenues. Ne mesurez pas le bonheur. Un mois sans papier national n’est pas forcément un échec si le contrat était régional. Un mois « plein de retours positifs » sans une seule URL n’est pas un succès.</p>
<p>Gardez les preuves. Elles serviront au second titre — et à comparer un autre prestataire.</p>

<h2>Questions fréquentes</h2>
<h3>Un mois de SP suffit-il pour un premier roman ?</h3>
<p>Rarement, si le livre n’a ni angle ni dates. Six à huit semaines, avec un dossier prêt avant le premier envoi, sont plus réalistes. Un mois peut suffire pour un titre déjà attendu ou une actualité locale forte.</p>
<h3>Faut-il envoyer le livre papier ?</h3>
<p>Pour une partie de la presse écrite et pour beaucoup de libraires, oui. Pour blogs, podcasts et certaines newsletters, un EPUB ou un PDF suivi d’un papier sur demande suffit souvent. L’AP doit le dire contact par contact, pas « on envoie tout en papier ».</p>
<h3>L’AP garantit-il des retombées ?</h3>
<p>Il peut garantir des actions (envois, relances, suivi). Il ne peut pas garantir une critique. Méfiez-vous des forfaits « 10 parutions assurées » : c’est souvent de l’achat d’espace ou des sites sans lecteurs.</p>
<h3>Presse et réseaux : même prestataire ?</h3>
<p>Possible, si les deux lignes sont chiffrées à part. Un community manager n’a pas un fichier rédactions. Un AP n’est pas forcément à l’aise sur BookTok. Deux compétences, deux preuves.</p>
<h3>Quand commencer ?</h3>
<p>Idéalement 6 à 10 semaines avant la disponibilité réelle du livre — fichiers stables, couverture définitive, ISBN, date. Commencer le jour de la livraison imprimeur, c’est courir après une pile déjà pleine.</p>

