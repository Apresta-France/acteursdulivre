<p>Les « retombées » se comptent en pièces, pas en impressions publicitaires. Un article de blog spécialisé, une chronique radio locale, une mise en avant libraire : trois preuves. Mille vues d’une story : une autre métrique, un autre contrat.</p>

<h2>Ce que l’attaché de presse n’est pas</h2>
<p>Ce n’est pas une agence de publicité. Ce n’est pas un community manager. Ce n’est pas un <a href="/metiers/agent-litteraire">agent</a> qui négocie un contrat d’édition. Ce n’est pas un attaché commercial qui force un dépôt en librairie. Chaque confusion produit un devis trop cher pour le mauvais service.</p>
<p>L’AP ne « garantit » pas de papier dans un titre national. Quiconque le garantit ment, ou vend de l’achat d’espace déguisé. Ce que l’on peut garantir : le nombre d’envois, le nombre de relances, la tenue du fichier, la transparence du suivi.</p>
<p>Pour le portrait, les photos d’ouvrage et les visuels de dossier, un <a href="/metiers/photographie">photographe</a> a son propre contrat de cession. L’AP peut les utiliser ; il ne les invente pas dans le forfait à 800 €.</p>

