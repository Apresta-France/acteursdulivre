  <li>Bookstagram / BookTok : précisez si c’est inclus, et à quel volume d’envois.</li>
</ul>
<p>Si l’AP « gère aussi les réseaux », c’est une autre ligne. Voir plus bas, et les prestations <a href="/prestations">presse et communication</a>.</p>

<h2>Relances, timing, retombées</h2>
<p>Un livre envoyé sans relance est un livre oublié. Une relance quotidienne est un spam. L’usage sérieux : une relance à 10–15 jours, une autre si un intérêt a été signalé, puis l’arrêt. Le compte rendu doit distinguer : envoyé, reçu, lu, programmé, publié, refus poli, silence.</p>
<p>Le timing compte plus que le slogan. Un premier roman de rentrée envoyé la dernière semaine d’août arrive dans une pile déjà perdue. Un polar régional six semaines avant une date locale (salon, rencontre en <a href="/metiers/librairie">librairie</a>) a une chance. L’AP qui accepte n’importe quelle date pour encaisser le mois ne vous rend pas service.</p>
<blockquote>
  <p>« Une retombée, ce n’est pas un like. C’est une publication, une antenne, une table, une invitation — quelque chose qu’un tiers a choisi. »</p>
