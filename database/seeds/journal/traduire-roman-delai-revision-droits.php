<h2>Qui révise une traduction littéraire&nbsp;?</h2>
<p>Trois regards se confondent trop souvent.</p>
<ol>
  <li>La <strong>relecture du traducteur</strong> — il relit sa propre version. Elle est dans le métier, pas «&nbsp;en plus&nbsp;».</li>
  <li>La <strong>révision</strong> — un second professionnel, idéalement bilingue, confronte source et cible, chasse les faux-sens, lisse le français. C’est un autre devis, parfois un autre nom.</li>
  <li>La <strong>correction orthotypographique</strong> — sur le français déjà révisé, une fois le texte stabilisé. Métier de <a href="/metiers/correction">correcteur</a>, pas de traducteur.</li>
</ol>
<p>En maison, la révision est souvent interne ou commandée par l’<a href="/metiers/edition">éditeur</a>. En autoédition, si personne ne la paie, elle n’existe pas. L’auteur qui «&nbsp;relit parce qu’il parle un peu la langue&nbsp;» n’est pas un réviseur. Il peut signaler un nom propre&nbsp;; il ne garantit pas le ton.</p>
<p>Budgétez la révision à part, ou exigez qu’elle soit nommée dans le devis de traduction. Un forfait unique qui dit «&nbsp;traduction + relecture&nbsp;» sans dire qui relit est un forfait flou.</p>

<h2>Que couvre la cession de droits&nbsp;?</h2>
<p>La traduction est une <strong>œuvre dérivée</strong>. Le traducteur détient des droits d’auteur sur sa version. L’auteur du roman source détient les droits sur l’original. Pour publier, il faut les deux chaînes&nbsp;: le droit de faire traduire, et le droit d’exploiter la traduction.</p>
<p>Cinq lignes à faire écrire, comme pour une illustration&nbsp;:</p>
<ul>
  <li><strong>langue</strong> (une seule, ou plusieurs)&nbsp;;</li>
  <li><strong>territoires</strong> (France, francophonie, monde)&nbsp;;</li>
  <li><strong>durée</strong> (années, ou vie de l’œuvre)&nbsp;;</li>
  <li><strong>supports</strong> — papier, numérique, <a href="/metiers/audio">audio</a>, feuilleton, lecture publique&nbsp;;</li>
  <li><strong>exclusivité</strong> et sort en cas de réédition, de changement de titre, de vente de droits à un tiers.</li>
</ul>
<p>Un «&nbsp;je vous vends la traduction&nbsp;» sans ces lignes ne dit pas si vous pouvez faire un livre audio, une édition poche, ou une cession à une maison. Un <a href="/metiers/juridique">juriste du livre</a> ou un <a href="/metiers/agent-litteraire">agent</a> sert précisément à ça lorsque les sommes dépassent un chapitre d’essai.</p>
<blockquote>
  <p>«&nbsp;On n’achète pas 80&nbsp;000 mots. On négocie une version, une langue, et ce qu’on a le droit d’en faire.&nbsp;»</p>
</blockquote>

<h2>Auteur, traducteur, éditeur&nbsp;: qui signe quoi&nbsp;?</h2>
<p>Si vous êtes l’auteur et que vous commandez la traduction de votre propre roman, vous signez un contrat de commande / cession avec le traducteur. Vous devez déjà détenir le droit de faire traduire — ce qui est le cas sur votre texte, sauf clause contraire déjà cédée.</p>
<p>Si vous traduisez le roman d’un autre, la première signature n’est pas celle du traducteur. C’est l’autorisation de l’auteur ou de ses ayants droit, souvent via l’agent ou la maison source. Traduire sans cette autorisation, même «&nbsp;pour voir&nbsp;», expose à devoir tout jeter.</p>
<p>L’éditeur, quand il existe, est souvent le cessionnaire. Il paie le traducteur, il exploite, il mentionne le nom (droit moral). En autoédition, vous jouez ce rôle&nbsp;: mention du traducteur sur la page de titre, exemplaires, et respect du contrat. Ce n’est pas un prestataire anonyme.</p>

<h2>Comment briefer un traducteur de roman&nbsp;?</h2>
<p>Un bon brief tient en une page et un dossier.</p>
<ul>
  <li>Fichier source définitif, ou version clairement datée si une dernière passe est encore ouverte.</li>
  <li>Nombre de mots et de signes, genre, public, niveau de langue visé.</li>
  <li>Noms propres, toponymes, déjà-traduits (une suite, un cycle).</li>
  <li>Ce qui doit rester en VO (chansons, citations, jeux de mots à annoter).</li>
  <li>Calendrier&nbsp;: essai, rendu intermédiaire, livraison, fenêtre de révision.</li>
</ul>
<p>Fournissez les éditions déjà parues. N’envoyez pas trois versions «&nbsp;au cas où&nbsp;». Pour comparer mot et feuillet de 1&nbsp;500 signes, voir le <a href="/journal">journal</a>&nbsp;: les fourchettes 18–28&nbsp;€ le feuillet et 0,12–0,22&nbsp;€ le mot ne se superposent pas sans conversion.</p>

<h2>Révision, relecture, épreuves&nbsp;: trois passes distinctes</h2>
<p>Après livraison, le français entre dans la chaîne du livre comme n’importe quel manuscrit. La <a href="/metiers/lecture-editoriale">lecture éditoriale</a> peut encore demander des coupes. Puis la correction. Puis la maquette. Puis les épreuves — où le traducteur a souvent un droit de regard sur sa version.</p>
<p>Prévoyez ce regard dans le calendrier et dans le contrat. Une modification d’éditeur qui recoud une phrase sans consulter le traducteur crée des faux-sens. Une correction typo, elle, n’a pas besoin d’un débat littéraire. Distinguez les deux dans les allers-retours.</p>
<p>Aucune de ces passes ne peut être déléguée à une IA générative sur Acteurs du Livre. Une «&nbsp;traduction automatique relue&nbsp;» n’est pas une traduction littéraire, et elle n’a pas de régime de droits clair. Page <a href="/confiance">Confiance</a>.</p>

<h2>Quel contrat pour une autoédition bilingue&nbsp;?</h2>
<p>Le minimum écrit&nbsp;: parties, œuvre source (titre, auteur, volume), langue cible, tarif et unité, délai, révision, cession (les cinq lignes), mention du nom, nombre d’exemplaires auteur/traducteur, et juridiction. Un échange de mails peut suffire pour un essai payé&nbsp;; pas pour 12&nbsp;000&nbsp;€.</p>
<p>Le paiement suit souvent un échéancier&nbsp;: acompte à la commande, solde à la livraison, parfois une part à la révision. Sur <a href="/">acteursdulivre.fr</a>, le règlement de la mission se fait hors site. Pas d’abonnement&nbsp;; la première mission du prestataire est offerte, puis 8&nbsp;% lui sont facturés. Voir <a href="/comment-ca-marche">comment ça marche</a> et les <a href="/tarifs">tarifs</a>.</p>
<p>Si une maison reprend ensuite le livre, relisez la cession. Vous ne pouvez céder à l’éditeur que ce que vous avez acquis. Une exclusivité mal bornée bloque la suite, ou oblige à renégocier avec le traducteur en urgence.</p>

<h2>Questions fréquentes</h2>
<h3>Peut-on traduire 80&nbsp;000 mots en un mois&nbsp;?</h3>
<p>Rarement sans casser le texte ou le tarif. Un mois calendaire, c’est le rythme d’une traduction utilitaire, pas d’un roman. Huit semaines utiles sont déjà un rythme soutenu.</p>
<h3>L’auteur doit-il relire la traduction&nbsp;?</h3>
<p>S’il est bilingue, il peut relire pour les faits et le ton. Ce n’est pas une révision professionnelle. S’il n’est pas bilingue, son rôle est le brief et la validation du calendrier, pas la chasse aux faux-sens.</p>
<h3>Le traducteur est-il payé en droits d’auteur ou au forfait&nbsp;?</h3>
<p>Les deux existent. En autoédition, le plus fréquent est un forfait au mot ou au feuillet, avec cession bornée. Un à-valoir plus des droits proportionnels suppose des ventes suivies et un éditeur qui reverse — rare en circuit court.</p>
<h3>Faut-il un agent pour une seule traduction&nbsp;?</h3>
<p>Pas forcément. Un contrat clair et, au besoin, une relecture par un <a href="/metiers/juridique">juriste</a> suffisent. L’<a href="/metiers/agent-litteraire">agent</a> devient utile dès qu’il y a plusieurs langues, un enchérisseur, ou une maison en face.</p>
<h3>Qui possède le titre français&nbsp;?</h3>
<p>Le titre se négocie. Il peut être une création du traducteur, une demande de l’auteur, ou un compromis. Faites-le figurer dans le contrat, surtout s’il devient la marque du livre en librairie.</p>

