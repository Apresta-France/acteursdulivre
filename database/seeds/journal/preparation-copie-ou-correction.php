<h2>Questions fréquentes</h2>
<h3>La préparation de copie remplace-t-elle la correction ?</h3>
<p>Non. Une prépa réduit le nombre de fautes, mais ce n’est pas son objet. Après une prépa, une passe orthotypographique reste le standard avant maquette et impression.</p>
<h3>Peut-on demander les deux au même prestataire ?</h3>
<p>Oui, si la personne exerce vraiment les deux métiers — et si les deux lignes apparaissent au devis, avec deux tarifs. Un forfait unique rend le contrôle impossible.</p>
<h3>Combien de temps prévoir entre prépa et correction ?</h3>
<p>Le temps que l’auteur arbitrage les propositions. Comptez au minimum une à deux semaines. Envoyer le fichier en correction le lendemain de la prépa, c’est geler des choix que vous n’avez pas lus.</p>
<h3>Un correcteur peut-il « faire un peu de prépa » dans la marge ?</h3>
<p>Il peut signaler. Il ne peut pas, au tarif d’une correction, restructurer un roman. Si le besoin apparaît en cours de mission, on reclasse le devis — on ne bricole pas.</p>
<h3>L’IA générative peut-elle faire le tri ?</h3>
<p>Pas sur Acteurs du Livre, et pas comme substitut. Un outil de chasse aux coquilles n’est ni une prépa ni une correction. Les manuscrits ne servent pas à entraîner un modèle. Page <a href="/confiance">Confiance</a>.</p>

