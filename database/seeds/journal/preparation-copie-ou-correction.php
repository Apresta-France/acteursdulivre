<h2>Que faut-il livrer au préparateur ou au correcteur ?</h2>
<p>Un fichier unique, version finale que vous assumez, pas un dossier de variantes. Indiquez le genre, le public, les choix déjà tranchés (tutoiement, temps verbal, orthographe rectifiée ou non). Signalez les citations, les langues étrangères, les noms propres inventés. Plus le brief est clair, moins le prestataire protège sa marge contre les allers-retours.</p>
<p>Pour une prépa, précisez ce qui est négociable et ce qui ne l’est pas. Un préparateur n’est pas là pour « améliorer le style » dans l’absolu : il est là pour rendre <em>ce</em> livre plus lisible, dans <em>vos</em> contraintes. Pour une correction, figez le code : dialogues à la française, capitales d’usage, abréviations.</p>
