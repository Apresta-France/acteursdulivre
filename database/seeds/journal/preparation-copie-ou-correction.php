<h2>Qu’est-ce qu’une préparation de copie ?</h2>
<p>La <strong>préparation de copie</strong> est un travail sur le texte avant qu’il ne soit figé pour l’impression. Le préparateur ou la préparatrice lit le manuscrit comme un objet à rendre publiable : plan, enchaînements, répétitions, tics de style, dialogues qui sonnent faux, personnages qui changent de prénom, ellipses qui cassent le rythme. Il annote, propose, parfois réécrit une phrase — toujours au service de l’auteur, pas à sa place.</p>
