<h2>Maquette, correction, traduction</h2>
<p>Le <a href="/metiers/maquette">maquettiste</a> livre un PDF d’impression. Les sources (InDesign, polices) ne sont à vous que si c’est écrit. Sans sources, vous re-payez une mise en pages à la moindre correction lourde ou au changement de format. C’est un livrable, pas un détail technique.</p>
<p>La <a href="/metiers/correction">correction</a> et la préparation de copie portent sur votre texte : le correcteur n’acquiert pas l’œuvre. Il reste titulaire de sa méthode, pas du roman. La <a href="/metiers/traduction">traduction</a> est une œuvre seconde : le traducteur a des droits sur sa version. Publier une traduction sans cession, même si vous avez écrit l’original, est un autre livre — et un autre contrat.</p>
<p>La <a href="/metiers/reliure">reliure</a> d’art et le façonnage n’entraînent pas de droits d’auteur sur le texte ; ils peuvent créer des droits sur un objet unique. Distinguez l’exemplaire artisanal et l’édition courante.</p>

<h2>Livre audio : ne pas tout mettre dans le même bon</h2>
<p>L’enregistrement ajoute l’interprète (et parfois un studio, une musique). Vous cédez — ou on vous cède — le droit d’exploiter <em>cette</em> fixation. Changer de narrateur, c’est un nouveau contrat. Mettre le fichier sur une plateforme, c’est une licence de plus, souvent non exclusive. Le texte reste le vôtre ; la voix n’est pas « comprise dans le roman ».</p>
<ol>
  <li><strong>Texte</strong> — licence audio distincte si un tiers produit le livre parlé.</li>
  <li><strong>Voix</strong> — cession de la prestation, mentions, exclusivité limitée dans le temps.</li>
  <li><strong>Musique / bruitages</strong> — droits tiers, souvent oubliés.</li>
  <li><strong>Fichier master</strong> — qui le détient, pour quels ré-encodages.</li>
</ol>

<h2>Ce que les plateformes prennent — et ce qu’elles ne prennent pas</h2>
<p>Une boutique ou un agrégateur demande en général le droit de vendre et de livrer le fichier, parfois une exclusivité temporaire. Relisez la résiliation et le délai de retrait. Ils n’ont pas à devenir coauteurs. Si l’ISBN est au nom de la plateforme, la notice dit « éditeur » : ce n’est pas une cession de votre texte, mais cela complique un changement de circuit. Voir aussi ISBN et dépôt légal dans le <a href="/journal">journal</a>.</p>
<p>Pour faire rédiger les cessions, utilisez les <a href="/prestations">prestations</a> juridiques. L’<a href="/inscription">inscription</a> est gratuite. La première mission du prestataire est offerte, puis 8 % lui sont facturés ; le règlement se fait hors plateforme (<a href="/tarifs">tarifs</a>). Les <a href="/prestataires">prestataires</a> illustration, photo et maquette doivent pouvoir montrer un modèle de cession.</p>
