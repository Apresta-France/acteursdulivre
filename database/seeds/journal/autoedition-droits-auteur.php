<h2>Le texte : ce qui est déjà à vous</h2>
<p>Le Code de la propriété intellectuelle protège l’œuvre originale dès qu’elle existe. Vous n’avez pas besoin d’ISBN ni de dépôt légal pour « avoir le copyright » — ces formalités concernent l’édition et la conservation, pas la naissance du droit. Le droit moral (nom, intégrité du texte) reste attaché à vous : un prestataire ne peut pas signer à votre place une réécriture qui dénature l’œuvre sans accord.</p>
<p>Ce que vous pouvez céder, ce sont les droits patrimoniaux : reproduire, représenter, adapter. En autoédition, vous les gardez le plus souvent, et vous accordez des licences (boutique, distributeur, anthologie). C’est l’inverse du contrat d’<a href="/metiers/edition">édition</a> classique, où une maison se fait céder l’exploitation. Relisez les conditions de chaque plateforme : licence exclusive ou non, durée, sortie.</p>
<p>Sur <a href="/">acteursdulivre.fr</a>, le manuscrit ne sert pas à entraîner un modèle. Aucun livrable texte n’est produit par une IA générative. Voir <a href="/confiance">Confiance</a> et <a href="/comment-ca-marche">comment ça marche</a>.</p>

<h2>Couverture, photo, iconographie</h2>
<p>L’<a href="/metiers/illustration">illustrateur</a> possède son dessin. Le <a href="/metiers/photographie">photographe</a> possède son cliché. L’<a href="/metiers/iconographie">iconographe</a> négocie des images déjà existantes : vous achetez un droit d’utilisation, rarement la photo. Sans contrat, vous avez le fichier pour un usage flou — et un refus le jour où vous voulez un poche, un bandeau, une affiche de salon ou une traduction.</p>
