<h2>Questions fréquentes</h2>
<h3>Si je paie un illustrateur, la couverture est à moi ?</h3>
<p>Seulement dans les limites de la cession. Sans écrit, l’usage raisonnable pour <em>ce</em> livre est parfois défendable, le reste (produits dérivés, autre titre, exclusivité mondiale) ne l’est pas. Faites la grille des cinq lignes avant le BAT.</p>
<h3>Puis-je réutiliser la même maquette chez un autre imprimeur ?</h3>
<p>Oui si vous avez les fichiers et le droit de les utiliser. Sinon, vous rachetez une adaptation. Demandez les sources et les polices (licences comprises) à la commande, pas après.</p>
<h3>Un correcteur peut-il revendiquer le livre ?</h3>
<p>Non sur le fond du roman. Il peut revendiquer le paiement et, exceptionnellement, s’opposer à une utilisation de ses annotations comme publication séparée. Ce n’est pas un coauteur du récit.</p>
<h3>Faut-il déposer le texte à la SGDL ou ailleurs ?</h3>
<p>Ce n’est pas constitutif du droit. Certains auteurs horodatent pour la preuve. Ce n’est pas un substitut aux cessions des images et de l’audio.</p>
<h3>L’autoédition me fait-elle perdre des droits face à une maison ?</h3>
<p>Non par magie. Une édition antérieure peut gêner une maison si les droits numériques sont encore licenciés en exclusivité. Avant de signer un contrat d’édition, dressez la liste des licences en cours et de leurs dates de fin.</p>

