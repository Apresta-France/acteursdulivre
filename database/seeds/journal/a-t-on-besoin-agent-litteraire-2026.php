<p>En France, en 2026, un agent littéraire prend le plus souvent <strong>10 à 15 %</strong> des sommes qu’il contribue à faire naître — droits d’auteur, à-valoir, parfois audio, traduction, audiovisuel selon le mandat. Il n’y a pas de tarif horaire « officiel ». Il y a un <em>mandat</em> : un périmètre, une durée, une exclusivité, et une commission. Sans ces quatre lignes, vous n’avez pas un agent. Vous avez une conversation.</p>
<p>La question n’est pas « est-ce prestigieux ». C’est : votre projet a-t-il besoin d’un intermédiaire pour atteindre des <a href="/metiers/edition">maisons</a>, négocier, ou suivre une carrière à plusieurs contrats ? Pour une majorité de premiers romans en envoi spontané ou en autoédition, la réponse est non — et ce n’est pas un échec. Les <a href="/metiers/agent-litteraire">agents</a> le disent eux-mêmes : ils ne peuvent pas tout prendre.</p>

<h2 id="essentiel">L’essentiel</h2>
<ul>
  <li>Commission usuelle : <strong>10 à 15 %</strong> sur les revenus du périmètre mandaté.</li>
  <li>L’agent vend un accès, une négociation et un suivi — pas une publication garantie.</li>
  <li>Le mandat doit dire : titres, droits (livre, audio, étranger…), durée, exclusivité.</li>
  <li>Utile dès qu’il y a plusieurs maisons, un contrat à discuter, ou des droits dérivés.</li>
  <li>Peu utile pour un unique envoi, une autoédition simple, ou un texte encore instable.</li>
</ul>

<h2>Ce que fait un agent littéraire — et ce qu’il ne fait pas</h2>
<p>L’agent lit, sélectionne, propose un manuscrit à des éditeurs ciblés, relance, compare des offres, discute à-valoir, périmètre de cession, délais. Il peut suivre les comptes, une <a href="/metiers/traduction">traduction</a>, un contrat <a href="/metiers/audio">audio</a>. C’est un métier de représentation, pas d’écriture. Il n’est pas coach, <a href="/metiers/correction">correcteur</a> ni attaché de presse. S’il promet la publication moyennant un forfait de lecture élevé, vous n’êtes plus dans l’usage français de l’agence : c’est une vente de service. En France, beaucoup de romans signent encore en envoi direct. L’agent change la donne quand le texte a déjà un niveau, et que le marché est encombré ou juridique.</p>

<h2>Mandat, commission, exclusivité</h2>
<p>Le <strong>mandat</strong> est le contrat. Il désigne les œuvres concernées (un titre, une œuvre à venir, un catalogue), les droits confiés (édition française, monde, audiovisuel, merchandising…), la durée, le préavis, et le sort des négociations en cours à la fin du mandat.</p>
<p>La <strong>commission</strong> de 10 à 15 % se calcule sur ce que l’auteur <em>perçoit</em> au titre des contrats obtenus dans le périmètre — pas sur le prix public du livre. Vérifiez : à-valoir, droits d’auteur, à-valoir audio, ventes de droits étrangers. Un agent qui prend 15 % sur l’étranger et 10 % sur la France, ou l’inverse, doit l’écrire. Les sous-agents à l’étranger ajoutent parfois une couche : le contrat doit dire qui paie quoi.</p>
<ul>
  <li>Exclusivité : l’auteur n’envoie plus le même texte en parallèle. C’est cohérent. Ce n’est pas une prison : durée et sortie doivent être prévues.</li>
  <li>Frais : envois, déplacements, copies — qui les avance, qui les déduit.</li>
  <li>Lecture payante : un vrai agent vit de la commission, pas d’une file d’attente tarifée. Une lecture éditoriale distincte, c’est un autre métier.</li>
</ul>
<p>Un <a href="/metiers/juridique">juriste du livre</a> relit un mandat plus vite que vous ne le regretterez. Surtout si l’exclusivité dépasse deux ans, ou si tous les droits futurs sont balayés d’une phrase.</p>

<h2>Quand l’agent change la trajectoire</h2>
<p>Trois situations reviennent.</p>
<p><strong>Plusieurs maisons possibles.</strong> L’agent évite les envois désordonnés et compare des offres — à-valoir, poche, numérique, clause d’épuisement. <strong>Contrats empilés</strong> (livre, audio, étranger, audiovisuel) : chaque avenant peut céder trop ; l’agent ou le juriste sert ici plus que pour « ouvrir la porte ». <strong>Une carrière, pas un titre</strong> : le mandat a du sens s’il y a quelque chose à orchestrer. Un premier roman encore en chantier n’en est pas là.</p>
<blockquote>
  <p>« L’agent ne rend pas un texte bon. Il rend un texte déjà bon plus négociable, et moins seul. »</p>
</blockquote>

<h2>Quand il ne sert pas — ou pas encore</h2>
<p>Le manuscrit n’est pas fini, ou il n’a jamais été lu par un tiers exigeant. Dans ce cas, une <a href="/metiers/lecture-editoriale">lecture éditoriale</a> ou une <a href="/metiers/beta-lecture">bêta-lecture</a> coûte moins cher qu’attendre une réponse d’agence six mois. L’agent n’est pas un comité de lecture gratuit à la chaîne.</p>
<p>Vous visez uniquement l’autoédition, sans cession à une maison, sans audio chez un éditeur, sans étranger. Il n’y a rien à mandater, sauf à transformer l’agent en conseiller — alors payez du conseil, pas 15 % sur des ventes qu’il n’a pas obtenues.</p>
<p>Vous avez déjà un éditeur, un contrat signé, et un seul titre sans droits dérivés en vue. Un juriste pour l’avenant suivant peut suffire. Prendre un agent <em>après</em> signature est possible, pour la suite : cela se négocie, ce n’est pas rétroactif sur le contrat déjà en place, sauf accord des trois parties.</p>
<p>Vous cherchez surtout de la visibilité. C’est de la <a href="/metiers/presse-com">presse</a>, de la librairie, des salons. L’agent n’est pas un community manager.</p>

<h2>Comment évaluer un mandat (et un silence)</h2>
<p>Un agent sérieux dit non souvent. Un silence de trois mois n’est pas un oui. Relancez une fois, puis passez à autre chose. N’envoyez pas le même texte à quinze agences en copie cachée si leurs sites demandent l’exclusivité de soumission : c’est le premier test de lecture des usages.</p>
