<h2>Premier roman, maisons, autoédition</h2>
<p>Un premier roman peut se passer d’agent. Il peut aussi en avoir besoin s’il est déjà abouti, dans un genre aux portes étroites, ou si l’auteur ne veut pas négocier seul. L’autoédition n’interdit pas un agent plus tard ; elle le rend inutile <em>sur le titre autoédité</em>, sauf mandat de cession à un tiers. Ne versez pas 15 % sur des ventes de salon que vous avez faites seul, sauf clause explicite — et alors, demandez-vous pourquoi. L’<a href="/inscription">inscription</a> est gratuite. Brief utile : genre, volume, état du texte, envois déjà faits, attente réelle. Pas « faites-moi publier ».</p>

<h2>Questions fréquentes</h2>
<h3>Un agent peut-il garantir une publication ?</h3>
<p>Non. Il peut garantir un travail d’envoi et de négociation dans un périmètre. Quiconque vend une publication contre un forfait n’exerce pas le métier d’agent au sens usuel : c’est une autre offre, à lire comme un service éditorial.</p>
<h3>10 ou 15 %, comment juger ?</h3>
<p>Moins par le pourcentage que par le périmètre. 10 % sur tout, y compris ce que vous négociez seuls, peut coûter plus cher que 15 % sur les seuls contrats qu’il obtient. Lisez la base de calcul et les exclusions.</p>
<h3>Puis-je avoir un agent et envoyer aussi en direct ?</h3>
<p>Pas si le mandat est exclusif sur ce titre — le cas le plus fréquent. Si vous tenez à des envois personnels (une maison précise, un contact), faites-les <em>avant</em> de signer, ou faites-les inscrire en exception.</p>
<h3>L’agent remplace-t-il un juriste ?</h3>
<p>Pas toujours. Sur un contrat complexe (audiovisuel, coproduction, cession large), les deux regards se complètent. L’agent connaît le marché ; le juriste connaît l’acte. Voir les <a href="/metiers/juridique">juristes</a>.</p>
<h3>Faut-il un agent pour l’audio ou la traduction ?</h3>
<p>Utile dès que ces droits ne sont pas déjà cédés en bloc à la maison, ou dès qu’une offre tierce arrive. Inutile si tout a déjà été cédé pour longtemps sans réserve : l’agent n’aura rien à vendre. Relisez d’abord votre contrat d’édition.</p>

