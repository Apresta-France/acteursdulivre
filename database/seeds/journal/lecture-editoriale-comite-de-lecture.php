<h2>Lecture éditoriale, bêta, correction : trois achats</h2>
<p>Le <a href="/metiers/lecture-editoriale">lecteur éditorial</a> se place du côté de l’éditeur : ce texte est-il défendable, pour qui, à quel stade, avec quels risques. Il peut recommander une refonte du début, un genre plus juste, une coupe, un travail de personnages — il ne livre pas le nouveau manuscrit. L’<a href="/metiers/ecriture">auteur</a> reste maître des phrases.</p>
<p>La bêta-lecture dit ce qu’un lecteur cible a compris, aimé, lâché. Utile, plus proche du vécu, moins tournée vers une ligne éditoriale ou un marché. La correction orthotypographique arrive quand le texte est stabilisé. Commander les trois sous le même nom, c’est s’assurer un malentendu sur le devis et sur la déception.</p>
