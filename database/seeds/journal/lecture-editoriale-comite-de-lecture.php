<h2>Après l’avis : quoi en faire</h2>
<p>Si le rapport nomme un problème de structure, une correction de fautes ne le résoudra pas. Si le public est mal ciblé, changer la couverture ne suffit pas. Traitez les recommandations comme une liste ordonnée, pas comme un verdict moral. Vous pouvez contester ; vous ne pouvez pas exiger que le lecteur « aime ».</p>
<p>Un second avis n’est utile que si le brief est le même et que vous avez déjà tranché une partie des points. Trois lectures contradictoires sans décision, c’est un comité involontaire — et une addition. Le <a href="/journal">journal</a> et l’<a href="/aide">aide</a> situent la suite (correction, maquette, contrats). Présentation : <a href="/a-propos">à propos</a>.</p>

<h2>Questions fréquentes</h2>
<h3>La lecture éditoriale garantit-elle une publication ?</h3>
<p>Non. Elle éclaire une décision — la vôtre ou celle d’une maison. Méfiez-vous de quiconque vend un « avis positif » comme sésame auprès d’éditeurs nommés.</p>
<h3>Faut-il faire une lecture éditoriale avant d’autoéditer ?</h3>
<p>Utile si vous doutez du public ou de la structure. Pas un passage obligé si le texte a déjà été préparé, corrigé, et que vous connaissez votre circuit. À 150–400 €, c’est un poste à arbitrer comme les autres, pas un rite.</p>
<h3>Le lecteur éditorial corrige-t-il les fautes ?</h3>
<p>Il peut signaler un niveau de langue ou des scories qui gênent la lecture. Ce n’est pas une correction professionnelle. Budgetez la <a href="/metiers/correction">correction</a> à part, après stabilisation.</p>
<h3>Quelle différence avec un comité de maison ?</h3>
<p>Le comité sert la ligne de <em>cette</em> maison, avec ses stocks et son catalogue. Un lecteur indépendant sert votre question (autoédition, envoi ciblé, refonte). Les critères ne sont pas superposables.</p>
<h3>Peut-on envoyer un extrait seulement ?</h3>
<p>Oui si c’est convenu (premiers chapitres, novella). L’avis sur 50 pages ne préjuge pas de la tenue à 350. Le prix doit alors être inférieur à une lecture complète — et le rapport doit le rappeler.</p>

