<h2>Comité de lecture : plusieurs voix, une décision</h2>
<p>En maison, le comité agrège des fiches, parfois contradictoires, et une ligne éditoriale déjà pleine. L’auteur ne reçoit pas toujours le détail : il reçoit une réponse. En atelier ou en collectif d’autoédités, un « comité » peut vouloir dire trois lecteurs payés ou bénévoles : exigez le format de la synthèse et le nom des critères (genre, longueur, public) avant d’envoyer 400 pages.</p>
<p>Un comité n’efface pas les biais ; il les multiplie et, au mieux, les discute. Un seul lecteur éditorial expérimenté peut être plus clair qu’un vote flou. L’inverse est vrai si vous cherchez à tester plusieurs publics. Ce n’est pas une question de prestige, c’est une question de brief.</p>
<p>Ni le comité ni le lecteur ne remplacent un <a href="/metiers/agent-litteraire">agent</a> pour placer le texte, ni un juriste pour un contrat. Enchaîner lecture puis envoi aux maisons sans retravailler le point de blocage nommé est un luxe que le manuscrit paie.</p>

<h2>Comment commander sans malentendu</h2>
<p>Envoyez le texte complet (ou le volume convenu), le nombre de signes, une note d’intention d’une page, le genre revendiqué, et ce que vous voulez comme verdict (publication maison, autoédition, concours, simple diagnostic). Dites si une bêta a déjà eu lieu. Un manuscrit encore en chantier « pour avoir un avis tôt » produit un avis sur un objet instable.</p>
<ol>
  <li><strong>Volume et délai</strong> — signes, date de rendu, une passe ou relecture d’un extrait révisé.</li>
  <li><strong>Livrable</strong> — pages, grille, entretien téléphonique inclus ou non.</li>
  <li><strong>Ligne de référence</strong> — le lecteur travaille-t-il « comme une maison X » ou en généraliste ?</li>
  <li><strong>Confidentialité</strong> — manuscrit non réutilisé, pas d’IA générative (page <a href="/confiance">Confiance</a>).</li>
  <li><strong>Suite</strong> — ce qui n’est pas inclus (préparation de copie, coaching d’<a href="/metiers/ecriture">écriture</a>).</li>
</ol>
