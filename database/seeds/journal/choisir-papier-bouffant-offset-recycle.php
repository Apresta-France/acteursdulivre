<h2>Le grammage change-t-il vraiment le prix ?</h2>
<p>Oui, mais rarement autant que l’on croit si l’on ne change que 10 g. Sur un tirage de 300 exemplaires brochés, passer de 80 à 90 g se sent sur la ligne papier et sur le port ; cela peut représenter une part notable de la fourchette 10-25 %. Passer de 70 à 90 g se voit sur la facture <em>et</em> dans la caisse.</p>
<p>Pour 300 romans brochés, un imprimeur livre se situe souvent entre 1 100 et 1 600 € hors port (ordre de grandeur 2026). Le papier n’est pas 25 % de 5 800 € de budget total : il est 10 à 25 % du <em>devis impression</em>. Le reste du livre — correction 620 à 1 100 €, maquette 700 à 1 400 € — ne dépend pas du grammage. Détail : <a href="/journal/cout-fabrication-roman-autoedition">coût de fabrication d’un roman</a>.</p>

<h2>Comment le papier impose-t-il le dos et la reliure ?</h2>
<p>Le dos se calcule : nombre de pages × épaisseur de la feuille, plus garde-fous. Un fichier de couverture livré « au hasard 14 mm » sera faux. Le <a href="/metiers/maquette">maquettiste</a> a besoin du papier nommé, pas de « bouffant » tout court. L’<a href="/metiers/reliure">atelier de reliure</a> ou l’imprimeur qui façonne le brochage a le dernier mot sur l’épaisseur réelle.</p>
<p>Changer de papier après la couverture, c’est recalculer le dos, parfois refaire un BAT. Dans un planning de salon, c’est la semaine qu’on n’a plus. Figez le papier avant la finale de couverture. Voir aussi <a href="/journal/maquette-interieure-livre">la maquette intérieure</a>.</p>
