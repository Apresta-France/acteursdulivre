<h2>Offset ou numérique : le papier est-il le même ?</h2>
<p>Pas toujours. L’impression à la demande impose souvent la gamme de l’opérateur : un « cream 80 » qui n’est pas le bouffant de votre imprimeur offset. Le rendu est plus plat, le blanc différent, le dos parfois surprenant. Ce n’est pas un défaut moral ; c’est un autre objet. Si vous testez en POD puis tirez 300 ex. en numérique court, prévenez les lecteurs — ou assumez deux mains.</p>
<p>L’offset devient pertinent vers 500 à 800 exemplaires. En dessous, le numérique court d’un imprimeur livre offre en général un meilleur compromis que le POD dès que l’on vise <a href="/metiers/librairie">dépôt en librairie</a> ou <a href="/metiers/salons">salons</a>.</p>

<h2>Recyclé, labels, « papier de l’éditeur » : que croire ?</h2>
<p>Les labels (FSC, PEFC, anges bleus, etc.) parlent de filière, pas de plaisir de lecture. Demandez le nom commercial de la feuille, pas seulement « écologique ». Un recyclé mal choisi jaunit ou poussière ; un offset certifié peut être excellent. L’argument environnemental se tient si l’on ne sur-imprime pas 2 000 exemplaires « au cas où ».</p>
<p>Le « papier maison » de l’imprimeur est souvent le mieux tarifé, parce qu’il est en stock. Un papier de fantaisie à faire venir pour 300 ex. mange la marge et le délai. Réservez les papiers rares aux petits tirages de <a href="/metiers/reliure">reliure</a> d’art, pas au premier roman de 300 pages.</p>

<h2>Comment arbitrer sans se ruiner ?</h2>
<p>Tenez un roman comparable dans la main. Demandez trois échantillons (70 / 80 / 90, ou bouffant / offset / recyclé). Faites chiffrer le <em>même</em> fichier sur deux papiers, port à part. Gardez le 80 g bouffant si vous hésitez : c’est la référence la plus comparable. Montez le grammage si le texte est court et que le livre « ne fait pas le poids ». Baissez-le si vous expédiez beaucoup.</p>
<p>Ne coupez pas la <a href="/metiers/correction">correction</a> pour offrir 10 g de plus : le lecteur oublie le papier d’un livre juste ; il n’oublie pas les fautes. Sur <a href="/">acteursdulivre.fr</a>, pas d’abonnement ; première mission offerte au prestataire, puis 8 % ; règlement hors plateforme. <a href="/comment-ca-marche">Fonctionnement</a>, <a href="/tarifs">tarifs</a>, <a href="/prestations">prestations</a>, <a href="/inscription">inscription</a>. Page <a href="/confiance">Confiance</a>.</p>

<h2>Questions fréquentes</h2>
<h3>Quel papier pour un premier roman de 300 pages ?</h3>
<p>Bouffant 80 g, intérieur crème, est le choix le plus simple à défendre et à comparer. 70 g si le volume est déjà épais et le port critique ; 90 g si le texte est plus court et que vous voulez de la main.</p>
<h3>Le papier recyclé est-il plus cher ?</h3>
<p>Pas toujours. Certaines gammes stockées sont au prix de l’offset courant ; d’autres, de niche, dépassent nettement. C’est l’échantillon et la ligne du devis qui tranchent, pas l’idée qu’on s’en fait.</p>
<h3>Faut-il le même papier en réimpression ?</h3>
<p>Oui si vous voulez le même livre. Notez le nom exact sur le bon à tirer. Un « équivalent » un an plus tard peut changer le dos et la teinte. Les lecteurs de la première édition le verront en librairie.</p>
<h3>La couverture a-t-elle le même papier que l’intérieur ?</h3>
<p>Non. La couverture est un carton (souvent 240 à 300 g) pelliculé ou non. L’intérieur est une feuille d’édition. Deux lignes, deux choix. Le pelliculé mat ou brillant change le toucher, pas la main de l’intérieur.</p>
<h3>Peut-on mélanger recyclé intérieur et couverture classique ?</h3>
<p>Oui. C’est même fréquent. L’essentiel est la cohérence visuelle (teintes) et le calcul du dos sur l’intérieur réel.</p>

