<h2>Qu’est-ce que la main d’un papier ?</h2>
<p>La main, c’est le rapport entre l’épaisseur et le grammage. Deux papiers de 80 g n’ont pas la même épaisseur ni le même toucher. Le <strong>bouffant</strong> est conçu pour donner du volume à peu de poids : un roman de 300 pages en 80 g bouffant paraît plus épais qu’en 80 g offset. C’est pourquoi les romans français y restent fidèles.</p>
<p>Le grammage (70, 80, 90 g) change le prix, oui — plus de matière, plus de poids, plus de port. Mais l’auteur sent surtout autre chose : un 70 g fait un livre mince, presque brochure ; un 90 g rassure en main et alourdit le carton d’expédition. L’arbitrage n’est pas « le plus cher », c’est « le livre que l’on a envie de tenir ».</p>

<h2>Bouffant, offset, recyclé : pour quel ouvrage ?</h2>
<p>Le bouffant intérieur crème ou blanc cassé reste le choix le plus fréquent pour un roman, une nouvelle, beaucoup de récits. Il fatigue moins l’œil en lecture longue que certains blancs bleutés. L’offset, plus fermé, plus lisse, convient aux essais annotés, aux textes avec schémas, parfois aux intérieurs qui recevront un peu d’<a href="/metiers/iconographie">iconographie</a> en noir.</p>
<p>Le recyclé a cessé d’être une contrainte morale illisible : plusieurs gammes tiennent la lecture. En revanche, la teinte (gris, crème irrégulier) et le petit « bruit » visuel du papier se voient. Montrez un échantillon à l’auteur et au <a href="/metiers/maquette">maquettiste</a> avant de figer le BAT. Un beau livre photo, lui, sort du trio : couchés, demi-mats, tout autre devis.</p>
