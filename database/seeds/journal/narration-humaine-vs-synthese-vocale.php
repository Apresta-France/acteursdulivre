<h2>Droits&nbsp;: qui possède une voix de synthèse&nbsp;?</h2>
<p>Une narration humaine s’appuie sur un contrat avec une personne&nbsp;: cession bornée (supports, durée, territoires), nom au générique, parfois exclusivité. C’est le même réflexe que pour une traduction ou une couverture.</p>
<p>Une voix de synthèse s’appuie sur <em>autre chose</em>&nbsp;: les conditions d’un logiciel, une licence de modèle, parfois le droit à l’image et à la voix d’une personne dont le timbre a été cloné. Si le modèle a été nourri de voix non consentantes, le risque ne se limite pas à un retrait de fichier. Il peut toucher le narrateur imité et l’éditeur qui commercialise.</p>
