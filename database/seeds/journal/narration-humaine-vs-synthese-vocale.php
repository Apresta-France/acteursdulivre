<h3>Toutes les plateformes refusent-elles la synthèse&nbsp;?</h3>
<p>Non. Les politiques divergent et bougent. Certaines acceptent des catalogues étiquetés. D’autres refusent ou cantonnent. Lisez le contrat du distributeur visé, pour l’année en cours, avant de produire.</p>
<h3>L’auteur qui se lit est-il «&nbsp;humain&nbsp;» au sens des règles&nbsp;?</h3>
<p>Oui, s’il parle réellement devant un micro. Ce n’est pas une synthèse, même si un logiciel nettoie le souffle. Le contrat et la fiche doivent le nommer comme narrateur.</p>
<h3>Cloner ma propre voix pour lire mon roman, est-ce permis ici&nbsp;?</h3>
<p>Non, si le fichier est généré par un modèle. Le fait que ce soit «&nbsp;votre&nbsp;» timbre ne change pas la nature du livrable. Ailleurs, cela reste un sujet de licence d’outil et de mention loyale auprès de l’auditeur.</p>
<h3>La synthèse peut-elle servir de maquette avant le studio&nbsp;?</h3>
<p>Comme brouillon personnel, hors plateforme, c’est votre choix. Ce brouillon ne remplace ni le brief d’un narrateur, ni un chapitre pilote humain. Ne le livrez pas comme prestation.</p>

