<h2>Pourquoi Acteurs du Livre interdit l’IA générative&nbsp;?</h2>
<p>La plateforme est une place de métiers. Un livrable texte, image ou voix produit par une IA générative n’est pas une prestation de <a href="/metiers/audio">narrateur</a>, de <a href="/metiers/traduction">traducteur</a> ou d’<a href="/metiers/illustration">illustrateur</a>. La règle est la même pour tous les métiers, pas un caprice anti-technologie.</p>
<p>Concrètement&nbsp;: vous pouvez commander une narration humaine, un montage, un master. Vous ne pouvez pas livrer, ni faire livrer, une voix synthétique présentée comme un travail de comédien. Les manuscrits et les extraits échangés ne servent pas à entraîner un modèle. Le détail est sur la page <a href="/confiance">Confiance</a> et dans l’<a href="/a-propos">à-propos</a>.</p>
