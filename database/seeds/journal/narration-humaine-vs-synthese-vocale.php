<h2>Comment déclarer une voix humaine sans ambiguïté&nbsp;?</h2>
<p>Sur la fiche du livre et dans le contrat&nbsp;: nom du narrateur, qualité (comédien, auteur), langue, durée estimée, nature «&nbsp;voix humaine enregistrée&nbsp;». Dans les métadonnées du distributeur, la même phrase. Pas de «&nbsp;voix IA assistée&nbsp;» dans un coin si le fichier est humain, et l’inverse encore moins.</p>
<p>Gardez les rushes et le contrat. En cas de contestation («&nbsp;cette voix ressemble à…&nbsp;»), vous montrez une séance, une facture, une personne. Une synthèse n’a pas cet extrait de preuve, ou elle a la preuve inverse&nbsp;: un log logiciel.</p>
<p>Un outil de nettoyage de bruit (déclick, souffle) n’est pas une voix inventée. La frontière utile est&nbsp;: <strong>qui a dit le texte&nbsp;?</strong> Un humain devant un micro, ou un système qui a produit la parole.</p>

