<h2>Qualité d’écoute&nbsp;: ce que l’oreille entend</h2>
<p>La synthèse a progressé sur la phrase neutre. Elle reste faible sur ce qui fait un roman&nbsp;: l’ironie, le sous-entendu, deux personnages qui se coupent, une phrase trop longue que le comédien respire, un silence qui n’est pas un blanc technique. L’auditeur de roman entend la convention. Il rend le fichier s’il a l’impression d’un GPS littéraire.</p>
