<h2>Qui détient l’original et les sources ?</h2>
<p>Sauf clause contraire, l’illustrateur reste propriétaire du dessin original et, souvent, des fichiers sources. Vous recevez un fichier d’exploitation (TIFF, PDF, JPG haute définition) calé pour l’imprimeur. Demander les calques « au cas où » n’est pas anodin : c’est une cession plus large, ou une prestation de livraison des sources, à chiffrer.</p>
<p>Le <a href="/metiers/maquette">maquettiste</a> a besoin d’un fichier imprimable, pas forcément du PSD. L’<a href="/metiers/edition">éditeur</a> (ou l’autoédité qui en assume le rôle) archive le contrat avec le fichier. Perdre le contrat et garder le JPG, c’est se lier les mains à la réimpression.</p>

<h2>Que se passe-t-il en cas de réédition ou de poche ?</h2>
<p>Si la clause est muette, il faut redemander. Ce n’est ni une mauvaise volonté ni une surprise : c’est le droit commun. Prévoyez dès le premier devis une ligne « réédition même illustration, même titre » avec un forfait (souvent une fraction du premier prix) ou un principe de renégociation. Pour une <a href="/metiers/traduction">édition traduite</a>, le territoire et la langue changent : nouvelle cession.</p>
<p>Le livre audio et la série dérivée sont les deux oubliés les plus coûteux. Un visuel de couverture qui devient jaquette de l’<a href="/metiers/audio">audio</a> n’est pas « le même livre » au sens des supports. Notez-le.</p>

<h2>Comment négocier sans gâcher la relation ?</h2>
<p>Arrivez avec l’usage réel, pas avec « tous droits, monde, perpétuité » par précaution. L’illustrateur défend son catalogue. Vous défendez votre exploitation. Le point de rencontre, c’est la liste des usages des vingt-quatre prochains mois, plus une option chiffrée pour le reste.</p>
<p>Sur <a href="/">acteursdulivre.fr</a>, la mission peut porter sur l’image <em>et</em> sur la rédaction des cinq lignes dans le devis. Pas d’abonnement : première mission offerte au prestataire, puis 8 % ; règlement hors plateforme. Voir <a href="/comment-ca-marche">comment ça marche</a> et les <a href="/tarifs">tarifs</a>. Les <a href="/prestations">prestations</a> et l’<a href="/inscription">inscription</a> permettent de lancer le brief. Page <a href="/confiance">Confiance</a> : aucun livrable image généré par IA.</p>

<h2>Quand faut-il un contrat plus long ?</h2>
<p>Dès qu’il y a coproduction, plusieurs auteurs d’images, une collection, une licence jeunesse, ou un ayants droit photographique. L’iconographe qui négocie des archives n’est pas dans le même contrat que l’illustrateur d’une couverture. Un conseil <a href="/metiers/juridique">juridique</a> sur une page coûte moins cher qu’un conflit à la réimpression. Les <a href="/prestataires">prestataires</a> de l’annuaire séparent en principe les métiers.</p>

<h2>Questions fréquentes</h2>
<h3>La mention « © Prénom Nom » sur la 4e suffit-elle ?</h3>
<p>Elle crédite. Elle ne cède rien. Le crédit est obligatoire moralement et souvent contractuellement ; ce n’est pas le contrat.</p>
<h3>Peut-on modifier l’illustration sans l’auteur ?</h3>
<p>Le droit moral s’y oppose en principe (intégrité de l’œuvre). Recadrer pour le dos, ajouter un bandeau : prévoyez-le. Recolorer, IA, collage : autre négociation, souvent un refus légitime.</p>
<h3>Une image de banque se cède-t-elle pareil ?</h3>
<p>Non. Vous achetez une licence du stock, avec ses propres limites (tirage, exclusivité, visage modèle). Ce n’est pas une cession d’œuvre originale. Lisez la licence, pas seulement le prix du clic.</p>
<h3>Qui paie si l’imprimeur demande un fichier plus grand ?</h3>
<p>La livraison d’un fichier aux normes (fond perdu, 300 dpi, profil) fait partie de la prestation illustration ou maquette. Une refonte de composition est une nouvelle mission. Figez le livrable : format, profil, dos.</p>
<h3>Acteurs du Livre archive-t-il les contrats ?</h3>
<p>La plateforme suit la mission ; le contrat d’auteur se signe et se conserve entre les parties. Le règlement est hors site. En cas de doute, page <a href="/aide">aide</a> et <a href="/a-propos">à propos</a>.</p>

