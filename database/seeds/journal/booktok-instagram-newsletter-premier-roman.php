<h2>Ce que les réseaux ne remplacent pas</h2>
<p>Ils ne remplacent pas la <a href="/metiers/correction">correction</a> ni une couverture professionnelle. Un clip ne rattrape pas un texte fauté. Ils ne remplacent pas une disponibilité en librairie : un lecteur convaincu qui ne peut pas commander le livre s’arrête là. Ils ne remplacent pas une date — rencontre, salon, club — où le livre devient un objet tendu.</p>
<p>Ils ne remplacent pas non plus une <a href="/metiers/edition">ligne éditoriale</a>. Un premier roman « pour tout le monde » se raconte mal en quinze secondes. Un angle (territoire, métier, forme, public) se raconte mieux. L’angle n’est pas un slogan marketing : c’est ce qui permet à un libraire ou à un créateur de le <em>placer</em>.</p>
<p>Enfin, ils ne remplacent pas le temps de lecture. Un roman de 350 pages demande des heures. Votre communication peut seulement donner une raison de les prendre.</p>

