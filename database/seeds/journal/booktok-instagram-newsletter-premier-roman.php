<p>En 2026, un premier roman peut exister sur BookTok et Instagram sans vendre cinquante exemplaires hors du cercle des proches. Il peut aussi se vendre en <a href="/metiers/librairie">librairie</a> avec un compte quasi vide. Les réseaux changent la <em>vitesse</em> à laquelle un titre circule. Ils ne remplacent ni le livre tenu, ni un relais humain, ni une date.</p>
<p>Ce texte ne promet pas une « stratégie virale ». Il pose trois questions utiles : combien de temps cela prend, ce que cela coûte, et quelles preuves regarder. Un auteur qui publie trois Reels par semaine sans newsletter ni dates libraires achète du bruit. Un auteur qui n’ouvre aucun canal n’a simplement aucun endroit où envoyer ceux qui ont aimé.</p>

