<h2>Questions fréquentes</h2>
<h3>Faut-il être sur BookTok pour vendre un premier roman ?</h3>
<p>Non. C’est un accélérateur possible, pas une condition. Beaucoup de titres se vendent encore par libraires, clubs, presse locale et bouche-à-oreille. Y aller sans temps disponible coûte plus qu’y renoncer.</p>
<h3>Combien de followers pour que « ça marche » ?</h3>
<p>Il n’y a pas de seuil. Mille lecteurs alignés sur votre genre valent mieux que trente mille comptes généraux. Mesurez les lectures et les demandes en librairie, pas le nombre d’abonnés.</p>
<h3>Peut-on tout déléguer ?</h3>
<p>On peut déléguer la presse, les photos, une partie des envois. Déléguer « votre voix » au quotidien coûte cher et se voit. Si vous déléguez, exigez un calendrier, des livrables et des preuves — pas une promesse de viralité.</p>
<h3>Les publicités sponsorisées valent-elles le coup ?</h3>
<p>Parfois, pour une date ou une précommande, avec un visuel propre et une cible étroite. Rarement comme unique levier d’un premier roman. Isolez ce budget (souvent 100 à 400 € de test) et tuez-le s’il n’amène aucune vente traçable.</p>
<h3>Quand commencer les réseaux ?</h3>
<p>Quand vous avez quelque chose à montrer : couverture, extrait, date. Ouvrir un compte six mois à l’avance sans matière épuise l’auteur et l’audience. Six à huit semaines avant parution suffisent pour la plupart des premiers romans.</p>

