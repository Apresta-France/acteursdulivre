<h2>Ce que les réseaux changent — et ce qu’ils ne changent pas</h2>
<p>Depuis le début des années 2020, une partie des ventes de fiction circule par recommandation filmée. En 2026, ce circuit est installé. Il favorise les livres qui se racontent en quinze secondes. Il défavorise les textes lents à pitcher — contrainte de format, pas jugement de valeur. Un lecteur doit encore trouver l’objet, et le livre doit tenir après l’extrait. Les réseaux n’ôtent ni l’ISBN, ni le métier d’<a href="/metiers/presse-com">attaché de presse</a>. La version sobre : <em>un</em> canal tenu trois mois, une newsletter, deux dates réelles. Le reste est du décor.</p>

<h2>BookTok : temps, formats, preuves</h2>
<p>BookTok n’est pas une campagne achetée en un clic. Formats utiles : réaction à une scène, pile thématique, coulisses d’écriture concrètes. Formats qui fatiguent : teasers vides, danses hors sujet. Vous créez vous-même : 4 à 8 heures par semaine. Vous envoyez des SP à des lecteurs-créateurs : livres, port, parfois une coordination. Un <a href="/metiers/presse-com">prestataire presse</a> peut gérer cette liste ; ce n’est pas « faire du TikTok » au quotidien.</p>
<p>Preuves à regarder : lectures terminées (pas seulement « reçu »), mentions du titre à l’écran, liens ou ISBN cités, et — plus rare — une hausse de commandes dans les quinze jours. Un million de vues sur une vidéo qui n’énonce pas le titre ne sert à personne. Un clip à 2 000 vues qui envoie du monde en librairie locale, si.</p>
<p>Méfiez-vous des forfaits « 50 influenceurs BookTok » sans critères de genre ni d’audience réelle. Demandez des exemples de titres comparables, pas un tableur de pseudos.</p>

<h2>Instagram : vitrine, pas caisse</h2>
<p>Instagram reste utile comme <strong>adresse</strong> : bio avec lien unique, grille lisible (couverture, citations courtes, dates, visages), stories le jour d’une rencontre. Il est médiocre comme unique point de vente. Les liens se perdent, les algorithmes changent, le compte peut être limité du jour au lendemain.</p>
<p>Ce qui aide un premier roman : trois à cinq visuels stables (couverture, portrait, objet-livre, une phrase, une date), plus une cadence tenable — deux publications par semaine valent mieux qu’un feu d’artifice en octobre puis le silence. Un <a href="/metiers/photographie">photographe</a> pour le portrait et l’ouvrage évite six mois de photos floues ; la cession doit citer les réseaux, le site et la 4e.</p>
<p>Le Bookstagram d’autrui fonctionne comme le SP : ciblage, envoi, relance sobre, preuves. Ce n’est pas de l’achat d’espace, sauf si le créateur le facture comme tel — alors c’est de la pub, à isoler au budget.</p>

<h2>Newsletter : le seul actif que vous possédez</h2>
<p>Un abonné e-mail n’appartient pas à un réseau tiers. C’est le seul canal où vous pouvez annoncer une réimpression ou une date sans supplier un algorithme. Pour un premier roman, l’objectif n’est pas 10 000 inscrits. C’est 150 à 400 personnes qui ont choisi de vous lire.</p>
<p>Une lettre toutes les trois ou quatre semaines suffit : une nouvelle vraie, un extrait, une date, un lien d’achat ou de réservation. Quotidien, vous vous épuisez et l’on se désinscrit. Inexistant, vous n’avez nulle part où renvoyer ceux qui découvrent le livre en décembre.</p>
<blockquote>
  <p>« Les réseaux empruntent de l’attention. La newsletter la rend, un peu, à heure fixe. »</p>
</blockquote>
<p>Le coût : un outil d’envoi (souvent 0 à 20 €/mois à ces volumes) et du temps de rédaction. Pas besoin d’une agence. Besoin d’une phrase d’inscription sur le site, en 4e de couverture, et sur la table de dédicace.</p>

