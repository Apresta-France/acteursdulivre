<h2>À qui envoyer — et à qui ne pas envoyer</h2>
<p>Envoyez à des personnes qui ont déjà parlé d’ouvrages comparables, pas à « la culture » d’un quotidien national en aveugle. Une liste de trente noms avec une phrase de justification chacun est plus professionnelle qu’une extraction de deux cents adresses. Vérifiez le destinataire : le stagiaire de 2019 n’est plus là ; le service courrier jette les colis sans nom.</p>
<p>N’envoyez pas à un critique dont la ligne est clairement autre (poésie expérimentale vs roman sentimental, essai vs jeunesse). N’achetez pas de « packs visibilité » qui promettent des articles. N’incluez pas vos cousins dans le décompte SP : ce sont des exemplaires auteurs.</p>
