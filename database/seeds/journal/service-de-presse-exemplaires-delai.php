<h2>Questions fréquentes</h2>
<h3>Faut-il envoyer le livre avant sa sortie en librairie ?</h3>
<p>Oui, dans la plupart des cas. La presse a besoin de temps de lecture et de bouclage. Un envoi le jour J sert surtout aux blogs très réactifs et aux libraires qui tiennent déjà le titre.</p>
<h3>Le service de presse numérique suffit-il ?</h3>
<p>Il suffit pour une partie des chroniques en ligne. Il ne suffit pas si vous visez la presse papier régionale ou un critique qui annote. Prévoyez les deux, en volumes différents.</p>
<h3>Peut-on relancer un journaliste qui n’a pas répondu ?</h3>
<p>Une fois, poliment, en rappelant l’ISBN et la date de parution. Pas de deuxième relance, pas de message sur les réseaux personnels. Le silence est une réponse.</p>
<h3>Les exemplaires SP sont-ils déductibles ?</h3>
<p>Si vous êtes en structure (micro, société), parlez-en à votre expert-comptable : ce sont souvent des charges, sous conditions. Ce n’est pas le sujet du communiqué, ni une raison d’envoyer plus.</p>
<h3>Un attaché de presse garantit-il des articles ?</h3>
<p>Non. Il garantit un travail de liste, d’envoi et de suivi. Les parutions dépendent des rédactions. Méfiez-vous de quiconque vend un nombre d’articles.</p>

