<h2>À quoi sert un service de presse ?</h2>
<p>Le <strong>service de presse</strong> (SP) consiste à offrir des exemplaires à des personnes dont le métier ou l’audience est de parler des livres : journalistes, chroniqueurs, libraires relais, programmateurs de festivals, parfois enseignants ou bibliothécaires identifiés. Ce n’est pas un stock de cadeaux pour la famille. Ce n’est pas non plus un achat d’article : une recension n’est due à personne.</p>
<p>En maison, le service est tenu par la <a href="/metiers/presse-com">presse et communication</a>, avec des listes à jour, des embargos et un calendrier calé sur les offices. En autoédition, vous construisez cette liste vous-même ou vous la commandez. Dans les deux cas, le SP a un coût unitaire — impression, enveloppe, affranchissement — qui sort du même compte que le tirage librairie.</p>
<p>Sur <a href="/">acteursdulivre.fr</a>, vous pouvez comparer une <a href="/prestations">prestation</a> d’attaché de presse ou publier une recherche. Voir <a href="/comment-ca-marche">comment ça marche</a>.</p>

