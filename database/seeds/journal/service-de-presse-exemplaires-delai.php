<h2>Papier, numérique, communiqué</h2>
<p>Beaucoup de journalistes livre travaillent encore sur papier : annotations, transport, pile de chevet. Le PDF est utile pour les blogs, les podcasts, les pigistes nomades, et comme double en cas de colis perdu. L’e-pub convient si votre fichier est propre — une maquette Word exportée à la va-vite se lit mal sur liseuse.</p>
<p>Chaque envoi papier devrait contenir : le livre, un communiqué d’une page (titre, auteur, ISBN, prix, date de parution, pitch, bio courte, contact), éventuellement un marque-page. Pas de goodies encombrants. Pas de lettre de quatre pages. Mentionnez si une dédicace ou un salon est déjà calé : cela donne une date à l’article.</p>
<p>Le communiqué n’est pas le quatrième de couverture recopié. Il dit pourquoi <em>maintenant</em> et pour <em>qui</em>. Un professionnel de la <a href="/metiers/presse-com">presse-com</a> ou de l’<a href="/metiers/ecriture">écriture</a> de dossier de presse le rédige en une vacation. Aucun livrable de ce type n’est produit par une IA générative sur Acteurs du Livre ; voir <a href="/confiance">Confiance</a>.</p>

<h2>Calendrier, suivi et budget</h2>
<p>Imprimez assez tôt pour affranchir sans express. Un livre qui arrive le jour de la sortie est déjà en retard pour une page livres hebdomadaire. Bloquez les adresses deux semaines avant l’envoi : congés, changements de rubrique, « on ne reçoit plus de SP non sollicités ».</p>
<ol>
  <li><strong>J–60 à J–45</strong> — liste figée, communiqué prêt, stock SP séparé du dépôt librairie.</li>
  <li><strong>J–40 à J–21</strong> — envois papier ; fichiers numériques datés (embargo si vous en posez un).</li>
  <li><strong>J–14</strong> — une relance unique aux destinataires qui ont accusé réception ou dont le colis est livré.</li>
  <li><strong>Semaine de sortie</strong> — disponibilité pour une interview, pas une tournée de relances.</li>
</ol>
<p>L’embargo n’a de sens que si la date de mise en vente est réelle. Tenez un tableau (nom, support, date, réponse) : ce n’est un argument pour le libraire que lorsque l’article existe. Chaque exemplaire SP a le même coût de fabrication qu’un exemplaire vendu, plus le port : un SP de 50 livres sur un tirage de 300 n’est pas anecdotique. Économisez sur les destinataires hors cible, pas sur la qualité du livre. Vingt envois soignés valent mieux que quatre-vingts colis bâclés.</p>
