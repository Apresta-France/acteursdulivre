<h2>Suivi, pilon, et ce qui fait tout rater</h2>
<p>Quatre à huit semaines après le dépôt, un message suffit : réassort, retrait, dédicace. Pas un décompte quotidien. S’il n’a rien vendu, demandez un retour propre. Si trois librairies de la même ville ont le titre, dites-le : un « exclusif » fantôme use la confiance plus vite qu’un refus.</p>
<p>Le pilon, c’est le coût de stock et de transport. Il arrive quand le dépôt était trop gros, trop tôt, trop flou, ou quand l’auteur disparaît. Erreurs typiques : trente exemplaires « pour être visible », pas d’ISBN, relances de commercial. Sans angle local ou événement, le livre concurrence des titres déjà demandés. Mieux vaut trois librairies à cinq livres, un article et une dédicace tenue, qu’un dépôt national fantaisiste.</p>
