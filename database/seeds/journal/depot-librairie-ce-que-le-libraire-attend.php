<h2>Qu’est-ce qu’un dépôt en librairie ?</h2>
<p>Le <strong>dépôt</strong> n’est pas une vente ferme. Le libraire expose s’il le juge utile, encaisse le prix public à la vente, vous reverse ce prix moins la remise, et renvoie (ou pilonne, selon l’accord) le reste. C’est le circuit historique du livre, distinct de l’achat ferme — rare pour un premier autoédité — et d’un « on verra » sans papier.</p>
