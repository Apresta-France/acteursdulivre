<h2>La présentation que le libraire attend</h2>
<p>Il attend un livre qui a l’air d’un livre, et un interlocuteur qui a l’air de savoir où il est. Couverture propre, dos lisible, ISBN et code-barres, prix TTC imprimé ou étiqueté, quatrième qui tient en dix secondes. Un roman mal massicoté, sans code, avec un prix au crayon, lui fait perdre du temps à la caisse et à l’inventaire.</p>
<blockquote>
  <p>« Je ne refuse pas l’autoédition. Je refuse le carton anonyme, la remise fantaisiste et l’auteur qui revient tous les trois jours demander si ça s’est vendu. »</p>
