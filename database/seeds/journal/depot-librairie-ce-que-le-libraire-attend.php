<h2>Questions fréquentes</h2>
<h3>Le libraire peut-il refuser un dépôt d’autoédité ?</h3>
<p>Oui, et c’est fréquent. Il n’a pas d’obligation d’exposer. Un refus poli (« pas notre ligne », « plus de place en nouveautés ») vaut mieux qu’un oui de courtoisie suivi d’un oubli en réserve. Demandez s’il préfère un ou deux exemplaires à l’essai plutôt que d’insister sur quinze.</p>
<h3>Faut-il un diffuseur pour déposer en librairie ?</h3>
<p>Non pour quelques points de vente locaux. Oui dès que vous visez un réseau : Dilicom, office, facturation centralisée. Un petit éditeur ou un prestataire de diffusion peut jouer ce rôle ; ce n’est plus le même budget ni le même délai.</p>
<h3>Qui paie les exemplaires retournés ?</h3>
<p>C’est à écrire. Souvent l’auteur-éditeur paie le retour, parfois le libraire accepte un échange sur place. Sans clause, le conflit porte sur quelques euros de colis — assez pour que personne ne recommence.</p>
<h3>Peut-on déposer sans ISBN ?</h3>
<p>En pratique, presque jamais. La caisse, l’inventaire et le réassort passent par le code. Un livre sans ISBN est un objet artisanal : certains libraires le prennent en dépôt local, la plupart non.</p>
<h3>Combien de temps laisser les livres en rayon ?</h3>
<p>Trois à six mois suffisent pour juger une rotation sur un premier titre. Au-delà d’un an sans vente, retirez. Un livre qui occupe une face pendant deux ans n’est pas « bien diffusé » : il est oublié.</p>

