<p>Joignez une feuille A4 : titre, auteur, ISBN, prix, genre, public, deux phrases de pitch, un angle local s’il existe, dates de dédicace, contact. Si un article local ou un <a href="/metiers/presse-com">attaché de presse</a> a un envoi prévu, dites-le : le libraire vend mieux ce dont on parle dehors.</p>
<p>Prenez rendez-vous. Le samedi, le libraire est en caisse. Le lundi matin, il peut regarder le livre. Apportez les exemplaires dans un état revendable — pas dans le sac du marché. Si le livre sort de chez l’<a href="/metiers/impression">imprimeur</a> avec des coins cornés, triez avant.</p>

<h2>Ce qui se décide par écrit le jour du dépôt</h2>
<p>Sans papier, vous n’avez ni créance ni recours, et le libraire n’a pas de pièce comptable. Le bon de dépôt — ou la facture « en dépôt » — fixe au minimum : quantité, prix public TTC, remise, date, identité des deux parties, délai avant retour, état exigé des exemplaires, et qui paie le port retour. Un e-mail de confirmation le soir même vaut mieux qu’une poignée de main seule.</p>
<p>Décidez aussi du <em>réassort</em> : s’il en vend trois, lui en laissez-vous deux de plus sans nouveau rendez-vous ? Et de la dédicace : une heure un samedi, ce n’est pas « je reste toute la journée ». Le libraire prépare une table ; vous amenez un stylo qui marche et vous ne quittez pas le stand pour un café de deux heures.</p>
