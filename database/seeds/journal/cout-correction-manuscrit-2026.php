<h2>Correction et préparation de copie : deux budgets</h2>
<p>Sur le même roman, la <em>préparation de copie</em> se situe plutôt entre 1 200 et 2 400 €. Elle retravaille cohérence, répétitions, rythme. Ce n’est pas « une correction plus chère ». Les confondre fausse tous les comparatifs. Le détail des deux objets est dans notre article sur la <a href="/journal/preparation-copie-ou-correction">préparation de copie et la correction</a>.</p>
<p>Une <a href="/metiers/beta-lecture">bêta-lecture</a> (180 à 450 €) peut précéder le tout : elle dit si le livre tient. Elle ne remplace ni la prépa ni la correction.</p>

<h2>Roman, essai, jeunesse : le même prix ?</h2>
<p>Le signe reste l’unité. Mais un essai annoté, un récit avec chronologie, un album jeunesse au texte court et aux contraintes de pagination ne se corrigent pas au même rythme. Le roman linéaire, dialogues à la française, est souvent le plus prévisible. L’essai avec 80 notes et des citations à vérifier l’est moins : le correcteur lit plus lentement, et il doit savoir jusqu’où il vérifie les sources — ce n’est pas de la <a href="/metiers/lecture-editoriale">lecture éditoriale</a>.</p>
<p>Pour un ouvrage illustré, coordonnez avec l’<a href="/metiers/iconographie">iconographe</a> et le <a href="/metiers/maquette">maquettiste</a> : les légendes se corrigent, elles aussi, et souvent trop tard.</p>

<h2>Faut-il corriger avant la maquette ?</h2>
<p>Oui. Corriger après mise en pages coûte plus cher et plus de temps : chaque coupe déplace les fins de ligne, les veuves, le folio, parfois le dos. L’ordre utile : texte stabilisé, correction (et prépa si besoin), maquette, épreuves, <a href="/metiers/impression">impression</a>.</p>
<p>La seconde passe sur épreuves n’est pas un luxe. Elle rattrape les fautes introduites en saisie, les coupures malheureuses, les titres de chapitre déformés. Prévoyez-la au devis initial, pas en urgence la semaine du BAT.</p>
<p>Le budget global d’un roman autoédité de 300 pages, 300 exemplaires, se situe souvent entre 3 400 et 5 800 € hors diffusion. La correction en est un poste majeur, pas le plus gros si l’on imprime — mais le plus visible dès qu’il manque. Voir <a href="/journal/cout-fabrication-roman-autoedition">le coût de fabrication d’un roman</a>.</p>

