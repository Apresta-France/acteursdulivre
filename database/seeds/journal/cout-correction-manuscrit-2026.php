<h2>Qu’est-ce qui fait vraiment varier le devis ?</h2>
<p>Moins la réputation du correcteur que l’état du texte. Un manuscrit déjà passé par une préparation de copie se corrige plus vite : on peut perdre un tiers du temps, parfois plus. Un premier jet encore lâche, au contraire, force le correcteur soit à refuser, soit à reclasse le devis en prépa.</p>
<p>Les autres leviers sont stables :</p>
