<h2>Trois mots, trois contrats</h2>
<p>L’<strong>accompagnement d’écriture</strong> désigne tout ce qui aide un auteur à avancer sans lui livrer le manuscrit. Encore faut-il dire <em>comment</em>. Une heure de conversation n’est pas une annotation de 80 pages. Un groupe mensuel n’est pas un mentorat d’un an.</p>
<p>Le <strong>coach</strong> vend en général des séances et, parfois, une relecture ciblée entre deux rendez-vous. Le <strong>mentorat</strong> vend une disponibilité et une trajectoire — plus qu’un chronomètre. L’<strong>atelier</strong> vend une place dans un groupe. Si le devis mélange les trois, demandez à le déplier. Sinon vous ne saurez pas ce qui manque le jour où le roman dérape.</p>

<h2>Le coaching : séances, plan, retours</h2>
<p>Un coaching utile a un objet. « M’aider à écrire » n’en est pas un. « Stabiliser le plan d’un roman de 90 000 mots d’ici huit semaines » en est un. « Débloquer le troisième acte » aussi. Plus l’objet est précis, plus la séance sert, et plus le forfait se justifie.</p>
<p>Ce que font la plupart des coachs sérieux : relire un extrait <em>avant</em> la séance, poser un diagnostic (structure, voix, rythme), donner des exercices ou une feuille de route, puis un compte rendu court. Ce qu’ils ne font pas : une <a href="/metiers/correction">correction orthotypographique</a>, une <a href="/metiers/beta-lecture">bêta-lecture</a> de manuscrit entier au tarif de l’heure, ni une réécriture fantôme.</p>
<ol>
  <li>Durée de séance (45, 60, 90 minutes) et préparation incluse ou non.</li>
  <li>Volume relu entre deux rendez-vous (signes ou pages), et délai de retour.</li>
  <li>Nombre de séances du cycle, et ce qui se passe si vous sautez une date.</li>
  <li>Livrable écrit : notes, plan annoté, ou seulement l’oral.</li>
</ol>
<p>Sans le point 2, « coaching avec relecture » signifie parfois trois pages, parfois un roman. Ce n’est pas le même métier.</p>

<h2>Mentorat : durée, limites, conflits d’intérêts</h2>
<p>Le mentorat littéraire, au sens professionnel, est plus rare que le mot. Il suppose une relation dans le temps — souvent six mois à deux ans — et un mentor qui a une expérience transmissible : publications, maisons, ou simplement une pratique d’accompagnement éprouvée. Ce n’est pas un titre.</p>
<p>Le contrat utile dit : fréquence des échanges, canal (visio, mail, commentaires), ce qui est lu, et ce qui ne l’est pas. Un mentor n’est pas un <a href="/metiers/agent-litteraire">agent littéraire</a>. S’il promet de « placer le livre », vous n’achetez plus du mentorat : vous achetez un mandat, avec d’autres règles.</p>
<p>Attention aux conflits. Un mentor qui édite, qui agentise ou qui vend ensuite une prestation de prête-plume doit le dire. Vous devez pouvoir changer de prestataire sans emporter un sentiment de trahison — et sans clause qui vous lie à sa maison.</p>

<h2>Ateliers et groupes : ce que vous achetez</h2>
<p>L’atelier vend un <strong>cadre</strong> : dates, consignes, groupe, animation. Le bénéfice réel, pour beaucoup d’auteurs, n’est pas la « magie du collectif » : c’est la date butoir et le regard d’autres lecteurs. Le coût à la séance paraît bas ; le coût au roman dépend du nombre de mois et de ce qui est réellement lu.</p>
<p>Demandez : taille du groupe, temps de parole par texte, volume maximal envoyé, et si l’animateur lit hors séance. Un atelier de dix personnes où chacun lit deux pages n’est pas un accompagnement de manuscrit. C’est autre chose, parfois très utile — à condition de ne pas en attendre une direction d’ouvrage.</p>
<blockquote>
  <p>« Un groupe fait avancer. Il ne remplace pas une lecture entière, ni une correction, ni une décision éditoriale. »</p>
</blockquote>
<p>Les stages intensifs (week-end, semaine) se situent souvent entre 180 et 450 €. Ils servent à démarrer ou à débloquer. Ils ne fabriquent pas un livre.</p>

<h2>Ce que l’accompagnement ne remplace pas</h2>
<p>Quatre métiers voisins, quatre livrables. Les mélanger dans un même forfait « je t’accompagne jusqu’au bout » rend le prix illisible et les responsabilités floues.</p>
<ul>
  <li><a href="/metiers/beta-lecture">Bêta-lecture</a> — rapport de lecteur sur un manuscrit <em>terminé</em> ou presque : cohérence, rythme, personnages.</li>
  <li><a href="/metiers/lecture-editoriale">Lecture éditoriale</a> — avis de positionnement : ligne, public, potentiel, pas un coaching de scène.</li>
  <li><a href="/metiers/correction">Correction</a> — langue, typographie, cohérence de surface, après stabilisation du texte.</li>
  <li>Prête-plume — écriture déléguée, autre contrat, autre budget (souvent des milliers d’euros).</li>
</ul>
<p>Si votre manuscrit est fini et que vous voulez savoir s’il « tient », ce n’est plus un coach qu’il vous faut en premier. C’est une lecture. Si le texte n’existe pas encore, le coach ou l’atelier sont plus justes qu’une bêta-lecture à vide.</p>

