<h2>Questions fréquentes</h2>
<h3>Combien de séances faut-il pour un premier roman ?</h3>
<p>Il n’y a pas de nombre magique. Un cycle de 6 à 8 séances sur un trimestre suffit souvent à stabiliser un plan et à débloquer les scènes décisives. Au-delà, vérifiez que vous n’achetez pas une dépendance — ou une réécriture déguisée.</p>
<h3>Le coach peut-il ensuite corriger le manuscrit ?</h3>
<p>Oui, si c’est un autre contrat, au tarif de la correction, après que le texte est stabilisé. Mélanger les deux dans le même forfait brouille le regard : on ne corrige pas bien un texte qu’on a aidé à inventer la veille.</p>
<h3>Atelier ou coaching individuel ?</h3>
<p>L’atelier coûte moins cher et donne un rythme. Le coaching coûte plus cher et s’adapte à <em>votre</em> manuscrit. Beaucoup d’auteurs font les deux, à des moments différents : groupe pour démarrer, individuel pour le nœud structurel.</p>
<h3>Un mentorat garantit-il une publication ?</h3>
<p>Non. Quiconque le promet vend autre chose — souvent de l’espoir. Un mentor peut ouvrir des lectures, relire un dossier, indiquer des maisons. Il ne signe pas le contrat d’édition à votre place.</p>
<h3>Faut-il un accompagnement si l’on vise l’autoédition ?</h3>
<p>Pas obligatoirement. Il est utile si vous bloquez, si le plan ne tient pas, ou si vous n’avez jamais fini un texte long. Il est superflu si le manuscrit est déjà solide : passez alors à la lecture, puis à la correction.</p>

