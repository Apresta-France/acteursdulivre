<p>En 2026, une traduction littéraire se facture en France <strong>0,12 à 0,22&nbsp;€ le mot source</strong>, ou <strong>18 à 28&nbsp;€ le feuillet de 1&nbsp;500 signes</strong>. Comparer deux devis sans convertir l’unité, c’est comparer deux métiers qui n’ont pas le même mètre.</p>
<p>Ces fourchettes sont celles du marché, pas des statistiques d’Acteurs du Livre. Elles aident à lire une offre de <a href="/metiers/traduction">traduction</a> avant de signer, surtout lorsqu’un prestataire compte au mot et l’autre au feuillet.</p>

<h2 id="essentiel">L’essentiel</h2>
<ul>
  <li>Deux unités circulent&nbsp;: le <strong>mot source</strong> (0,12–0,22&nbsp;€) et le <strong>feuillet de 1&nbsp;500 signes</strong> (18–28&nbsp;€).</li>
  <li>Elles ne sont pas équivalentes tout seules&nbsp;: convertissez avant de dire «&nbsp;moins cher&nbsp;».</li>
  <li>Le signe se compte sur le texte source, espaces comprises — et la règle doit être écrite.</li>
  <li>Un devis complet dit aussi&nbsp;: révision, notes, délai, cession.</li>
  <li>Un roman de 80&nbsp;000 mots, au tarif littéraire au mot, sort souvent entre <strong>9&nbsp;600 et 17&nbsp;600&nbsp;€</strong>.</li>
</ul>

<h2>Signe, mot, feuillet&nbsp;: de quoi parle-t-on&nbsp;?</h2>
<p>Le <strong>signe</strong>, dans l’édition française, est un caractère, espace comprise. On dit aussi «&nbsp;caractère espaces comprises&nbsp;» (cec). Le <strong>feuillet</strong> professionnel vaut en général <strong>1&nbsp;500 signes</strong>. C’est l’unité historique des correcteurs, des préparateurs et de beaucoup de contrats maison.</p>
<p>Le <strong>mot source</strong> est l’unité la plus fréquente en traduction littéraire et en traduction éditoriale «&nbsp;au volume&nbsp;». On compte les mots du texte à traduire, pas ceux de la langue cible. Un anglais compact et un allemand composé ne pèsent pas le même nombre de mots pour la même idée&nbsp;: d’où l’intérêt, parfois, de revenir au signe.</p>
<p>Une page Word n’est une unité de rien. Corps, marges et interligne la font varier de 1&nbsp;200 à 2&nbsp;800 signes. Un devis «&nbsp;à la page&nbsp;» sans définition est incomparable. Les <a href="/metiers/correction">correcteurs</a> le savent&nbsp;; les traducteurs aussi. Exigez le même compteur des deux côtés.</p>

<h2>Pourquoi le signe plutôt que le mot&nbsp;?</h2>
<p>Le signe est stable. Il ne dépend pas de la langue, ni des traits d’union, ni de la façon dont un logiciel coupe «&nbsp;aujourd’hui&nbsp;». Un feuillet de 1&nbsp;500 signes reste 1&nbsp;500 signes, que le texte soit français, italien ou anglais. Les maisons d’édition l’utilisent pour aligner traduction, <a href="/metiers/lecture-editoriale">lecture éditoriale</a> et correction sur la même règle.</p>
<p>Le mot parle aux traducteurs formés au marché international. Il est simple à expliquer («&nbsp;80&nbsp;000 mots, 0,15&nbsp;€&nbsp;») mais il pénalise ou favorise selon la langue source. Un devis au mot anglais n’est pas un devis au mot français.</p>
<p>Aucun des deux n’est «&nbsp;plus honnête&nbsp;». Un tarif à 22&nbsp;€ le feuillet n’est pas automatiquement plus doux qu’un tarif à 0,14&nbsp;€ le mot. Il faut ramener les deux au même volume, sur le <em>même fichier</em>.</p>

<h2>Combien coûte une page de roman traduit&nbsp;?</h2>
<p>Une «&nbsp;page&nbsp;» de roman n’existe pas tant qu’on n’a pas dit le nombre de signes. En ordre de grandeur, un feuillet à 18–28&nbsp;€ représente le travail sur 1&nbsp;500 signes source. Au mot, 250 mots à 0,12–0,22&nbsp;€ donnent 30 à 55&nbsp;€ — ce qui montre déjà que les deux barèmes du marché ne se recouvrent pas terme à terme.</p>
