<p>Un français courant tourne souvent autour de <strong>5 à 6 signes par mot</strong>, espaces comprises — à vérifier sur le fichier, pas sur une moyenne inventée. 80&nbsp;000 mots peuvent donc faire 400&nbsp;000 à 480&nbsp;000 signes, soit environ 270 à 320 feuillets. À 18–28&nbsp;€, la fourchette tombe alors vers <strong>4&nbsp;800 à 9&nbsp;000&nbsp;€</strong>. L’écart avec le barème au mot est précisément la raison de cet article.</p>
<p>La langue, le genre (prose, théâtre, poésie, notes de bas de page) et le délai expliquent le reste. Une traduction «&nbsp;courante&nbsp;» de guide n’est pas une traduction de roman. Voir aussi le délai et les droits dans l’article sur le métier, et les <a href="/metiers/edition">éditeurs</a> qui imposent leur unité.</p>

<h2>Comment convertir un devis au mot en devis au signe&nbsp;?</h2>
<p>Trois étapes, toujours sur le texte source.</p>
<ol>
  <li>Obtenez le <strong>nombre de mots</strong> et le <strong>nombre de signes espaces comprises</strong> du même fichier (traitement de texte, mêmes options).</li>
  <li>Divisez les signes par 1&nbsp;500 pour avoir des feuillets, ou multipliez les feuillets par 1&nbsp;500 pour revenir aux signes.</li>
  <li>Ramenez chaque devis au <strong>prix total</strong> et au <strong>prix pour 1&nbsp;000 signes</strong> (ou pour 1&nbsp;000 mots). C’est ce couple qui se compare.</li>
</ol>
<p>Exemple de méthode, pas de statistique de plateforme&nbsp;: 0,16&nbsp;€ le mot sur 80&nbsp;000 mots = 12&nbsp;800&nbsp;€&nbsp;; 24&nbsp;€ le feuillet sur 300 feuillets = 7&nbsp;200&nbsp;€. B n’est «&nbsp;moins cher&nbsp;» que si les 300 feuillets couvrent tout le livre — notes et citations comprises. Écrivez la règle de comptage (espaces, chiffres, textes déjà traduits).</p>

<h2>Ce que le devis doit inclure</h2>
<p>L’unité ne suffit pas. Un devis de traduction littéraire utile tient en une page et dit&nbsp;:</p>
<ul>
  <li>langue source et cible, genre, volume (mots <em>et</em> signes), fichier de référence&nbsp;;</li>
  <li>tarif et unité, total, échéancier&nbsp;;</li>
  <li>nombre de passes, <strong>révision incluse ou non</strong>, et par qui&nbsp;;</li>
  <li>notes du traducteur, bibliographie, poésie ou dialogues versifiés&nbsp;;</li>
  <li>délai, et ce qui se passe en cas de manuscrit encore instable&nbsp;;</li>
  <li>cession&nbsp;: langue, territoire, durée, supports (papier, numérique, audio).</li>
</ul>
<p>La révision par un second professionnel n’est pas une relecture de l’auteur. C’est un métier, parfois facturé à part, proche d’une <a href="/metiers/correction">correction</a> bilingue. Si elle n’est pas dans le devis, elle n’est pas dans le prix.</p>
<p>Les manuscrits ne servent pas à entraîner un modèle. Aucune traduction livrée sur Acteurs du Livre ne peut être produite par une IA générative. Voir <a href="/confiance">Confiance</a>.</p>

<h2>Comment comparer deux traducteurs&nbsp;?</h2>
<p>Après conversion des unités, reste le travail. Demandez un extrait déjà publié ou une courte passe d’essai payée (une ou deux pages, tarif au pro rata). Un essai gratuit de vingt pages n’est pas une pratique saine&nbsp;: c’est du travail non rémunéré.</p>
<p>Regardez les langues de travail réelles et des références de livres nommés. Les <a href="/prestations">prestations</a> à prix affiché aident quand l’unité est écrite.</p>
<p>Sur <a href="/">acteursdulivre.fr</a>, pas d’abonnement. La première mission du prestataire est offerte, puis 8&nbsp;% lui sont facturés. Le règlement se fait hors site. Mode d’emploi&nbsp;: <a href="/comment-ca-marche">comment ça marche</a> et <a href="/tarifs">tarifs</a>.</p>

<h2>Quel budget pour un roman de 80&nbsp;000 mots&nbsp;?</h2>
<p>Au barème littéraire au mot source, prévoyez <strong>9&nbsp;600 à 17&nbsp;600&nbsp;€</strong> pour le seul temps de traduction, hors révision externe et hors droits d’adaptation. Au feuillet, le total dépend du nombre de signes réel&nbsp;: d’où l’obligation de compter avant de comparer.</p>
<p>Ajoutez du calendrier. Un tel volume ne se livre pas en trois semaines sans casser la qualité — et sans majorer le tarif. Le délai, la révision et la cession font l’objet d’un autre texte du <a href="/journal">journal</a>. Ici, retenez&nbsp;: l’unité est le premier filtre, le total est le deuxième, le livrable (qui révise, qui possède quoi) est le troisième.</p>
<p>Mieux vaut un chapitre d’essai payé au tarif visé, puis un contrat sur le livre, qu’un chapitre «&nbsp;pour voir&nbsp;» au tarif bas que l’on ne pourra pas tenir sur 300 pages.</p>

<h2>Questions fréquentes</h2>
<h3>Le feuillet de 1&nbsp;500 signes inclut-il les espaces&nbsp;?</h3>
<p>Oui, dans l’usage éditorial français courant. Faites-le écrire. «&nbsp;1&nbsp;500 caractères&nbsp;» sans «&nbsp;espaces comprises&nbsp;» est une autre unité, plus généreuse pour le prestataire, plus chère pour vous.</p>
<h3>Faut-il compter les mots de la langue source ou cible&nbsp;?</h3>
<p>La source. La cible n’existe pas encore, et elle gonfle ou rétrécit selon les langues. Un devis au mot cible est une porte ouverte au conflit.</p>
<h3>Pourquoi deux fourchettes aussi éloignées&nbsp;?</h3>
<p>Parce que ce sont deux traditions de facturation, pas une conversion officielle. Le mot littéraire 0,12–0,22&nbsp;€ et le feuillet 18–28&nbsp;€ coexistent. On les compare après avoir mesuré le fichier, pas avec un coefficient universel.</p>
<h3>La préparation de copie se facture-t-elle pareil&nbsp;?</h3>
<p>Non. C’est un autre métier, souvent au feuillet, sur le texte français. Ne mélangez pas un devis de <a href="/metiers/traduction">traducteur</a> et un devis de préparateur ou de <a href="/metiers/correction">correcteur</a>.</p>
<h3>Peut-on payer au forfait livre&nbsp;?</h3>
<p>Oui, si le forfait repose sur un volume mesuré et une liste de livrables. Un forfait «&nbsp;roman&nbsp;» sans signes ni mots n’est pas un prix&nbsp;: c’est une enchère à l’aveugle.</p>

