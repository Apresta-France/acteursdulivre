<h2>Comment briefer sans tout raconter trop tôt</h2>
<p>Un bon brief de ghostwriting ressemble à un brief d’édition, pas à une confidence. Genre, public, volume, ton (trois adjectifs suffisent), ce qui est déjà écrit, ce qui est interdit (sujets, noms, ton « développement personnel » si vous n’en voulez pas), et la mention de signature souhaitée.</p>
<p>N’envoyez pas le manuscrit familial à dix profils : un extrait, un plan, puis les pièces sensibles au prestataire retenu, sous NDA. La page <a href="/confiance">Confiance</a> rappelle le cadre : travail humain, manuscrits non utilisés pour entraîner un modèle. Si vous hésitez encore à déléguer l’écriture, un accompagnement ou une lecture éditoriale coûte moins cher — et dit parfois que le prête-plume n’est pas le bon outil.</p>

<h2>Questions fréquentes</h2>
<h3>Le prête-plume peut-il revendiquer le livre plus tard ?</h3>
<p>Pas si le contrat cède les droits d’exploitation et organise l’invisibilité. Le droit moral existe toujours : d’où l’intérêt d’une clause de modifications et d’un livrable clairement accepté. En cas de doute, un juriste du livre relit avant signature.</p>
<h3>Faut-il un chapitre test ?</h3>
<p>Oui, dès que le livre dépasse quelques milliers d’euros. Un chapitre payé (400 à 1 200 €) teste la voix, le rythme et la relation de travail. C’est moins cher qu’un roman à jeter à la page 80.</p>
<h3>La correction est-elle incluse ?</h3>
<p>Rarement une correction professionnelle complète. Le prête-plume livre un texte propre ; l’orthotypographie et la préparation de copie restent des métiers distincts, à budgéter après stabilisation du manuscrit.</p>
<h3>Peut-on payer au pourcentage sur les ventes ?</h3>
<p>Oui, surtout si une maison est visée. Le forfait reste la norme en autoédition : les ventes sont incertaines, et le prête-plume avance des semaines de travail. Un mix forfait + intéressement se négocie par écrit, avec une base de calcul claire (prix hors taxes, droits d’auteur perçus, etc.).</p>
<h3>Un prête-plume remplace-t-il un éditeur ?</h3>
<p>Non. Il écrit. Il ne fabrique pas le livre, ne le diffuse pas et ne le défend pas en librairie. Après le manuscrit : correction, maquette, fabrication, éventuellement presse. Chaque métier a son contrat.</p>

