<h2>Qu’est-ce qu’une mission de prête-plume ?</h2>
<p>Le <strong>prête-plume</strong> (ghostwriting) écrit un texte que le commanditaire publiera sous son nom, ou sous un nom choisi. Ce n’est ni un coaching, ni une <a href="/metiers/correction">correction</a>, ni une <a href="/metiers/lecture-editoriale">lecture éditoriale</a>. Le livrable est un manuscrit, pas un avis ni une séance.</p>
<p>Le métier recouvre des intensités très différentes : entretiens et archives, réécriture d’un premier jet, ou écriture à partir d’un plan. Ces missions n’ont pas le même prix ni le même calendrier. Les grouper sous « rédaction » rend les devis incomparables. En France, le droit moral est inaliénable : le contrat organise l’invisibilité (confidentialité, cession des droits d’exploitation, engagement de ne pas revendiquer la paternité publique). Ce n’est pas un implicite.</p>

<h2>Volume, délai et livrables : ce qu’il faut figer</h2>
<p>Le volume se compte en <strong>signes espaces comprises</strong>, ou en mots, jamais en « pages A4 Times 12 ». Une page Word n’est pas une page livre. Un roman de 300 pages imprimées représente souvent 450 000 à 550 000 signes. Si le devis dit « 250 pages » sans unité, le conflit est déjà dans la pièce.</p>
<p>Demandez aussi le nombre de versions (plan, premier jet, version après retours), le format du fichier, et le hors champ — notes, annexes, dialogues à retravailler. Un prête-plume n’est pas un éditeur à demeure. À figer : unité et volume cible ; dates de plan, de jet et de finale ; qui produit entretiens et documents ; une passe de retours groupés plutôt qu’une réécriture au fil de l’eau. Les <a href="/prestations">prestations à prix affiché</a> le précisent en principe. Un appel trop vague attire des réponses trop vagues. Voir <a href="/comment-ca-marche">comment ça marche</a>.</p>

<h2>Qui signe ? Nom sur la couverture et mentions</h2>
<p>Trois situations courantes, trois mentions différentes.</p>
<ul>
  <li><strong>Nom seul du commanditaire</strong> — le prête-plume n’apparaît nulle part. C’est le cas le plus fréquent en récit de vie et en « livre d’expert ».</li>
  <li><strong>Avec la collaboration de…</strong> — mention en page de titre ou en copyright. Plus rare en fiction, plus fréquent en essai.</li>
  <li><strong>Co-signature</strong> — ce n’est plus du ghostwriting. C’est une œuvre de collaboration, avec un autre partage des droits.</li>
</ul>
<p>Le contrat doit aussi dire ce qui se passe <em>autour</em> du livre : biographies, dossiers de presse, interviews. Un commanditaire qui raconte « j’ai tout écrit seul » alors que le prête-plume a un cercle professionnel étroit crée un risque pour les deux. Trancher : silence total, ou phrase convenue.</p>
<blockquote>
  <p>« La couverture n’est pas le seul endroit où l’on signe. La bio, le dossier de presse et les interviews comptent autant. »</p>
</blockquote>
<p>Si une <a href="/metiers/edition">maison d’édition</a> entre ensuite dans le circuit, elle voudra savoir qui détient quoi. Un contrat flou entre vous et le prête-plume devient alors le problème de trois personnes.</p>

<h2>Confidentialité : ce que le NDA doit couvrir</h2>
<p>La clause de confidentialité n’est pas une phrase de politesse. Elle vise le manuscrit, les entretiens, les documents, parfois l’existence même de la mission, et une durée — souvent plusieurs années après publication. Prévoyez les exceptions : <a href="/metiers/juridique">juriste</a>, expert-comptable, correcteur ou bêta-lecteur liés par la même obligation. Sans cette liste, personne ne peut relire ni chiffrer une <a href="/metiers/correction">correction</a>. Le NDA empêche de parler ; il ne dit pas qui peut publier, adapter ou enregistrer.</p>

<h2>Droits : cession, rémunération, suites</h2>
<p>En matière de ghostwriting, la rémunération est le plus souvent <strong>forfaitaire</strong> : vous achetez un manuscrit et les droits d’exploitation convenus. Une participation aux ventes (pourcentage sur droits d’auteur) existe, surtout si le prête-plume est identifié ou si le projet vise une maison. Les deux se cumulent parfois : un forfait bas plus un intéressement. C’est un autre contrat, pas une « option » orale.</p>
<p>Cinq lignes à écrire, comme pour une <a href="/metiers/illustration">illustration de couverture</a> :</p>
<ul>
  <li>droits cédés (reproduction, représentation, adaptation, traduction, audio) ;</li>
  <li>supports (papier, numérique, audio, extraits presse) ;</li>
  <li>territoires et langues ;</li>
  <li>durée (ou pour la durée des droits) ;</li>
  <li>exclusivité, et ce qui se passe en cas de suite, spin-off ou série.</li>
</ul>
<p>Le droit moral — notamment le respect de l’œuvre — reste. Si vous prévoyez une réécriture lourde ensuite, dites-le : le prête-plume cadrera un livrable définitif et une clause de modifications. Pour une <a href="/metiers/traduction">traduction</a> ou une version <a href="/metiers/audio">audio</a>, vérifiez que la cession les couvre. Sinon vous rachèterez.</p>

