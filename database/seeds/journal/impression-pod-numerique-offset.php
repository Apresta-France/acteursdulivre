<h2>À partir de quel volume l’offset devient-il rentable&nbsp;?</h2>
<p>Sur le marché français 2026, l’offset commence à parler à partir de <strong>500 à 800 exemplaires</strong> pour un roman noir intérieur. En dessous, la plaque et le calage mangent l’économie unitaire. Au-dessus, le coût à l’exemplaire baisse franchement — à condition d’écouler le stock.</p>
<p>Le seuil exact dépend du nombre de pages, du format et du papier. Un 400 pages grand format bascule plus tard qu’un 200 pages poche. Demandez toujours <em>deux</em> lignes sur le même devis&nbsp;: 300 et 800 exemplaires, même papier. La différence vous dit si l’offset vaut le délai.</p>
<p>Le piège n’est pas le prix de la plaque. C’est le carton de 800 livres dans un garage, plus le port retour si le roman ne tourne pas. L’offset n’est pas «&nbsp;plus professionnel&nbsp;»&nbsp;: il est plus économique <em>si</em> le volume est réel — salons, <a href="/metiers/librairie">dépôt en librairie</a>, précommandes.</p>

<h2>Papier, couverture et rendu&nbsp;: ce que le procédé change</h2>
<p>Le lecteur ne voit pas le procédé. Il sent le papier et il juge le dos. Un POD courant utilise souvent un couché ou un offset mince, moins «&nbsp;livre&nbsp;» qu’un bouffant d’imprimeur. Les noirs sont plus mats, les aplats de couverture plus sensibles aux micro-rayures. Ce n’est pas toujours visible en photo&nbsp;; ça l’est en main.</p>
<blockquote>
  <p>«&nbsp;Le procédé se choisit sur un exemplaire réel, pas sur un tarif unitaire. Un livre trop plat se vend moins bien qu’un livre un peu plus cher.&nbsp;»</p>
</blockquote>
<p>Le numérique court, chez un imprimeur qui travaille le livre, se rapproche de l’offset sur un intérieur texte. L’écart se creuse sur les photos, les aplats et les couvertures à fort encrage. L’offset reste supérieur pour les teintes stables et les grands tirages couleur.</p>
<p>Exigez un <strong>bon à tirer papier</strong>, pas seulement un PDF annoté. Vérifiez le dos (calculé sur le grammage commandé), le pelliculage (mat, brillant, soft-touch) et les fonds perdus. Un fichier de <a href="/metiers/maquette">maquettiste livre</a> en PDF/X évite la moitié des allers-retours.</p>

<h2>Quand l’impression à la demande suffit</h2>
<p>La POD est un outil de test, pas un défaut. Elle suffit pour offrir, envoyer cinq services de presse, vérifier la pagination, ou vendre en ligne sans stock. Elle convient aussi aux titres à rotation lente, réimprimés par dizaines.</p>
<p>Elle cesse de suffire dès que vous visez trois salons, un dépôt de 10 exemplaires chez plusieurs libraires, ou un prix public serré. À 6&nbsp;€ de fabrication et 30 à 40&nbsp;% de remise libraire, la marge disparaît. Le tirage court redevient l’option rationnelle.</p>
<p>Attention aux forfaits qui bundlent ISBN, diffusion et impression&nbsp;: le coût unitaire cache souvent un papier imposé. Comparez avec un imprimeur indépendant. Les <a href="/prestations">prestations</a> se lisent poste par poste.</p>

<h2>Comment lire un devis d’imprimeur&nbsp;?</h2>
<p>Ramenez deux devis à la même liste. Un «&nbsp;moins cher&nbsp;» qui oublie le pelliculage ou le port n’est pas moins cher.</p>
<ul>
  <li>Format fini, nombre de pages, impression recto-verso, noir ou couleur.</li>
  <li>Papier <em>nommé</em> (marque, grammage, bouffant ou offset), pas une catégorie vague.</li>
  <li>Couverture&nbsp;: carton, pelliculage, rabats, vernis sélectif.</li>
  <li>Façonnage&nbsp;: broché dos carré collé, cousu, tranchefile — et qui le fait.</li>
  <li>Quantité, délai, BAT papier, conditionnement, franco ou port à part.</li>
</ul>
