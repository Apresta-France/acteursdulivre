<h2>Quel procédé pour un premier roman autoédité&nbsp;?</h2>
<p>Pour un premier roman, le schéma le plus fréquent reste&nbsp;: quelques POD pour le texte et le cercle proche, puis un <strong>tirage numérique de 200 à 400 exemplaires</strong> une fois le fichier figé. L’offset attend d’avoir une raison de stock — une tournée, une précommande, un diffuseur.</p>
<p>Calculez à l’envers. Prix public, remise libraire 30 à 40&nbsp;%, exemplaires offerts, port. Si le POD mange toute la marge, le tirage court n’est pas un luxe&nbsp;: c’est la condition pour vendre autrement qu’en ligne au prix fort.</p>
