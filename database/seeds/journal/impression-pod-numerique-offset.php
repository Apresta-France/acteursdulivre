<h2>Qu’est-ce qui distingue POD, numérique et offset&nbsp;?</h2>
<p>Trois procédés se partagent le livre broché. L’<strong>impression à la demande</strong> (POD) produit un exemplaire, ou une poignée, à partir d’un fichier stocké chez un prestataire. Le <strong>numérique court</strong> tire une série — souvent 100 à 400 exemplaires — sur une presse toner ou jet d’encre, chez un <a href="/metiers/impression">imprimeur livre</a>. L’<strong>offset</strong> grave des plaques et n’est rentable que lorsque le volume absorbe la mise en route.</p>
<p>Ce n’est pas une hiérarchie de prestige. C’est une arithmétique&nbsp;: coût d’entrée, coût unitaire, délai, et ce que le papier accepte. En autoédition, le choix se fait trop tôt si le nombre de pages et le grammage ne sont pas figés&nbsp;: le dos se calcule sur le papier réel, et inverser l’ordre, c’est recommencer la <a href="/metiers/maquette">maquette</a>.</p>

<h2>Combien coûte un tirage de 300 exemplaires&nbsp;?</h2>
<p>Pour un roman courant, intérieur noir, couverture souple pelliculée, papier bouffant 80&nbsp;g, un imprimeur livre facture en général <strong>1&nbsp;100 à 1&nbsp;600&nbsp;€</strong> hors port pour 300 exemplaires. C’est la fourchette déjà utilisée dans l’article sur le <a href="/journal/cout-fabrication-roman-autoedition">coût de fabrication d’un roman autoédité</a>.</p>
<p>Le même volume en POD, à 4 à 8&nbsp;€ l’unité, sort entre <strong>1&nbsp;200 et 2&nbsp;400&nbsp;€</strong>. L’entrée est plus simple — pas de minimum, pas de palette — mais la note dépasse souvent le tirage court dès que l’on sort du test. Et le port, facturé à la commande, s’additionne à chaque réimpression.</p>
