<h2>Questions fréquentes</h2>
<h3>L’impression à la demande est-elle moins chère&nbsp;?</h3>
<p>À l’entrée, oui. À l’exemplaire, non, dès que le volume dépasse quelques dizaines. Pour 300 brochés, un imprimeur livre à 1&nbsp;100–1&nbsp;600&nbsp;€ est souvent plus économique qu’une POD à 4–8&nbsp;€ l’unité, et le papier est en général plus «&nbsp;livre&nbsp;».</p>
<h3>Faut-il un BAT papier avant de lancer 300 exemplaires&nbsp;?</h3>
<p>Oui. Un BAT écran ne montre ni le grammage, ni le dos réel, ni le pelliculage. Un exemplaire de contrôle coûte moins cher qu’une série entière à reprendre.</p>
<h3>Peut-on mixer POD et tirage court&nbsp;?</h3>
<p>Oui, et c’est souvent le plus sain&nbsp;: POD pour tester et réassort minute, tirage court pour les salons et le dépôt. Gardez le même fichier et le même papier autant que possible, sinon les deux versions se distinguent en rayon.</p>
<h3>L’offset vaut-il le délai pour un roman&nbsp;?</h3>
<p>Seulement si vous avez un débouché pour 500 à 800 exemplaires ou plus. Sinon vous financez du stock, avec un délai plus long.</p>
<h3>Qui choisit le papier, l’auteur ou l’imprimeur&nbsp;?</h3>
<p>L’imprimeur propose ce qu’il a en machine. Vous validez un nom et un grammage par écrit. Un maquettiste qui a déjà travaillé avec cet atelier évite les mauvaises surprises de dos et de marge.</p>

