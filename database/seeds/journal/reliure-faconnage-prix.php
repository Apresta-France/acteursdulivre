<p>Le piège est de demander un «&nbsp;vrai livre relié&nbsp;» pour 200 exemplaires sans budget. L’atelier refusera ou proposera un cartonnage industriel — un autre métier. Distinguez dès le brief&nbsp;: série ou pièce, cuir ou toile, délai (souvent 6 à 12 semaines en artisanal).</p>
<p>Une <a href="/metiers/illustration">illustration</a> ou une <a href="/metiers/photographie">photographie</a> pour les plats doit arriver aux bonnes dimensions, fonds perdus compris. Le relieur n’est pas graphiste.</p>

<h2>Dos, tranchefile et gardes&nbsp;: ce qui change le prix</h2>
<p>Trois détails reviennent sur les devis et expliquent les écarts.</p>
<ol>
  <li><strong>Le dos</strong> — droit ou arrondi, toilé ou imprimé, avec ou sans nerfs. Il se calcule en millimètres à partir du nombre de pages et du grammage. Un 70&nbsp;g et un 90&nbsp;g n’ont pas le même dos. Changer le papier après coup, c’est refaire la couverture.</li>
  <li><strong>La tranchefile</strong> — ce petit cordon en tête et queue. Décorative en série, structurelle en reliure cousue. Elle a un coût unitaire faible en machine, élevé à la main.</li>
  <li><strong>Les gardes</strong> — feuilles qui lient le corps d’ouvrage aux plats. Blanches, teintées ou imprimées. Une garde illustrée implique un fichier, une impression à part, parfois un calage couleur.</li>
</ol>
<p>Ajoutez le <em>capital</em> (rainure d’ouverture) et le <em>rogne</em>. Ce sont des défauts d’atelier, pas de fichier&nbsp;: d’où un exemplaire de contrôle avant la série.</p>

