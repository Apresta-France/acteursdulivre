<h2>Questions fréquentes</h2>
<h3>Le cartonnage double-t-il le prix d’un roman&nbsp;?</h3>
<p>Non. En série, il ajoute souvent 0,80 à 2,50&nbsp;€ par exemplaire, plus l’adaptation de la maquette. Ce qui double le budget, c’est une reliure artisanale appliquée à toute la série — ce qu’il ne faut en général pas faire.</p>
<h3>Dos carré collé et cousu, quelle différence pour le lecteur&nbsp;?</h3>
<p>Le cousu s’ouvre à plat et vieillit mieux. Le collé simple est plus raide et plus fragile à la charnière. Sur un roman lu une fois, l’écart est discret. Sur un ouvrage consulté, il est décisif.</p>
<h3>Faut-il un relieur en plus de l’imprimeur&nbsp;?</h3>
<p>Pour un broché de série, non&nbsp;: l’imprimeur façonne. Pour un cartonnage particulier, une petite série cousue ou une pièce unique, oui. Deux interlocuteurs, deux devis, un transport à prévoir.</p>
<h3>Peut-on relier après coup des exemplaires déjà brochés&nbsp;?</h3>
<p>Oui, c’est même un classique du tirage de tête&nbsp;: on réserve des feuilles ou l’on débroche quelques volumes. C’est plus cher que de le prévoir avant, et le format des plats doit être recalculé.</p>
<h3>La dorure au fer est-elle dans la fourchette 0,80–2,50&nbsp;€&nbsp;?</h3>
<p>Rarement. Cette fourchette couvre un cartonnage de série courant. Une dorure à la feuille, un fers gravé, un titre à la main sortent du forfait et se chiffrent à part, surtout en artisanal (vers le haut de la fourchette 40–180&nbsp;€, ou au-delà).</p>

