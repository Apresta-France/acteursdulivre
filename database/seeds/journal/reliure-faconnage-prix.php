<h2>Quel façonnage pour un roman autoédité&nbsp;?</h2>
<p>Pour un premier roman destiné aux <a href="/metiers/librairie">librairies</a> et aux salons, le <strong>broché dos carré collé</strong> reste le choix rationnel&nbsp;: il rentre dans les bacs, à un prix public tenable. Le cartonnage se justifie pour un beau livre, un album ou une édition de tête.</p>
<p>Gardez la reliure artisanale pour peu d’exemplaires et beaucoup de main. Ne coupez pas le façonnage pour sauver la couverture&nbsp;: un bel habillage sur un dos qui se fend déçoit plus qu’une couverture typographique sur un broché solide.</p>
