<h2>Qu’est-ce que le façonnage d’un livre&nbsp;?</h2>
<p>Le <strong>façonnage</strong> commence quand les feuilles sont imprimées. On plie, on assemble, on colle ou l’on coud, on pose la couverture, on rogne. C’est ce qui fait d’une pile de cahiers un livre qui s’ouvre et qui tient debout. La <em>reliure</em> désigne plutôt les ouvrages cousus, cartonnés ou travaillés à la main&nbsp;; dans le langage d’atelier, les deux mots se recouvrent.</p>
<p>En série, le façonnage est souvent dans le devis de l’imprimeur. En pièce ou en petite série soignée, c’est un <a href="/metiers/reliure">relieur</a> distinct. Mélanger les deux dans un «&nbsp;forfait livre&nbsp;» rend le prix illisible&nbsp;: on ne sait plus si l’on paie une colle industrielle ou une couture au fil.</p>
<p>Le façonnage fixe aussi la <strong>durée de vie</strong> du volume. Un dos collé bon marché se fend&nbsp;; un cousu s’ouvre à plat&nbsp;; un cartonnage survit aux salons. Ce n’est pas du luxe abstrait.</p>

<h2>Broché, dos carré collé, cousu&nbsp;: quelles différences&nbsp;?</h2>
<p>Le <strong>broché</strong> français courant, pour un roman, est un dos carré collé&nbsp;: les cahiers (ou le bloc fraisé) reçoivent une colle, puis une couverture souple. C’est le standard des 300 exemplaires à 1&nbsp;100–1&nbsp;600&nbsp;€. La variante «&nbsp;dos carré collé cousu&nbsp;» ajoute une couture des cahiers avant l’encollage&nbsp;: le livre s’ouvre mieux, le devis monte.</p>
<p>Le <strong>cousu</strong> artisanal assemble les cahiers au fil avant de poser les plats. C’est le travail de relieur, pas une option de presse. On le réserve aux livres d’artiste et aux exemplaires de tête — rarement à toute une série.</p>
<p>Dos arrondi, tranchefile, gardes toilées changent le geste et le prix. Demandez un ouvrage déjà fait dans la même technique. Les <a href="/prestataires">prestataires</a> sérieux ont des références en main.</p>

