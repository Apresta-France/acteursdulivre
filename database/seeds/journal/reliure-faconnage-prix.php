<h2>Quand payer une reliure artisanale&nbsp;?</h2>
<p>Entre <strong>40 et 180&nbsp;€ l’exemplaire</strong>, la reliure de métier s’adresse à autre chose qu’un roman de diffusion. On y va pour un livre d’artiste, un ouvrage de famille, une restauration, un tirage de tête de 20 ou 30 pièces, un cadeau d’entreprise unique. Le prix suit le matériau (toile, cuir, papier fait main), le nombre de cahiers et le décor.</p>
<blockquote>
  <p>«&nbsp;On ne relie pas un roman de salon à 40&nbsp;€ pièce pour toute la série. On relie dix têtes, et le reste reste broché.&nbsp;»</p>
