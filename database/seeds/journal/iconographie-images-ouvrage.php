<h2>Comment se négocient les droits d’une image ?</h2>
<p>Par l’usage : support (papier, numérique), tirage, format dans la page, territoire, durée, exclusivité. Les musées, les fonds de presse, les photothèques n’ont pas les mêmes grilles. L’iconographe sait qui demander, dans quel ordre, et quand une image « parfaite » est trop chère pour le chapitre.</p>
<p>Le domaine public n’est pas un sésame automatique : encore faut-il une reproduction de qualité, et parfois un droit du photographe de la photo de l’œuvre. Les portraits de personnes vivantes, les œuvres contemporaines, les façades d’architectes : autant de cas où un avis <a href="/metiers/juridique">juridique</a> évite une légende naïve.</p>
<blockquote>
  <p>« On ne négocie pas « une image ». On négocie un usage, un tirage et une légende. »</p>
</blockquote>

<h2>Qui écrit les légendes ?</h2>
<p>L’auteur peut les rédiger ; l’iconographe les aligne sur les crédits et les faits. Une légende fausse (date, attribution, lieu) est une faute éditoriale, pas un détail. La <a href="/metiers/correction">correction</a> des légendes doit être prévue : elles arrivent souvent après le corps du texte, trop tard pour la passe principale.</p>
<p>Crédits : la forme « © Nom / Institution / Année » n’est pas décorative. Elle est contractuelle. Un oubli en 4e ou en table des illustrations peut suffire à bloquer une réédition. Prévoyez une page ou un cahier d’illustrations dès la <a href="/metiers/maquette">maquette</a>.</p>

<h2>Faut-il un photographe ou un iconographe ?</h2>
<p>Si les images n’existent pas encore — reportage, objets, portraits d’auteur — c’est une commande <a href="/metiers/photographie">photo</a>, avec cession propre. Si elles existent quelque part (archives, presse, collections), c’est de l’iconographie. Beaucoup d’ouvrages ont besoin des deux : un reportage de couverture, un corpus intérieur sourcé.</p>
<p>L’<a href="/metiers/illustration">illustration</a> originale (schéma, carte, reconstitution) est un troisième levier quand l’archive est trop chère ou inexistante. Une carte claire à 300-600 € remplace parfois trois photos mediocres à 150 € pièce.</p>

<h2>Comment briefer sans noyer le prestataire ?</h2>
<p>Un sommaire, le public, le format du livre, le nombre d’images cible, le budget droits plafond, les interdits (visages, marques, scènes sensibles), la date de BAT. Joignez les passages du manuscrit qui appellent une image. « Mettez de belles photos » n’est pas un brief ; « une vue du chantier avant 1914, droits France, tirage 800 ex. » en est un.</p>
<p>Décidez tôt si les images sont documentaires (on montre la chose) ou d’ambiance (on évoque). Les deux se sourcent autrement, et se maquettent autrement. Un essai trop « beau livre » rate sa démonstration ; un beau livre trop « essai » rate sa page.</p>

<h2>Où placer l’iconographie dans le calendrier et le budget ?</h2>
<p>Avant la maquette définitive, pas la semaine du PDF imprimeur. Les délais musée se comptent en semaines. Dans un budget d’ouvrage illustré, la mission 400-1 800 € est souvent inférieure aux droits. Couper l’iconographe pour « chercher soi-même » déplace le temps sur l’auteur et le risque sur l’<a href="/metiers/impression">imprimeur</a> — qui, lui, n’est pas juriste.</p>
