<h2>Qu’est-ce que l’iconographie d’un livre ?</h2>
<p>L’<a href="/metiers/iconographie">iconographe</a> trouve les images dont le texte a besoin, vérifie qu’on peut les publier, négocie ou oriente la négociation, rédige ou cadre les légendes et les crédits, et livre un dossier exploitable par le maquettiste. Ce n’est ni un <a href="/metiers/photographie">photographe</a> de commande, ni un illustrateur, ni un documentaliste « qui envoie des liens ».</p>
