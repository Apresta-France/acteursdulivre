<h2>Questions fréquentes</h2>
<h3>Peut-on publier une image trouvée sur Wikimedia ?</h3>
<p>Parfois, si la licence et le fichier le permettent, et si vous respectez le crédit. « Wikimedia » n’est pas une autorisation unique. Vérifiez chaque fiche, chaque auteur, chaque restriction de territoire.</p>
<h3>L’iconographe paie-t-il les droits pour vous ?</h3>
<p>Sauf mandat clair, non. Il prépare le dossier, parfois relance, parfois avance pour un client habituel. Le payeur reste l’éditeur ou l’auteur. Distinguez honoraires et débours au devis.</p>
<h3>Faut-il des images dans l’e-pub si le papier est illustré ?</h3>
<p>Si les droits le permettent. Beaucoup de licences papier excluent le numérique, ou le facturent à part. C’est une des cinq questions à poser dès la première demande d’autorisation.</p>
<h3>Qui archive les autorisations ?</h3>
<p>Vous. Le prestataire livre une copie du dossier. À la réédition, c’est ce classeur — pas le souvenir d’un e-mail — qui permet de réimprimer. Perdre les PDF d’autorisation, c’est renégocier à froid.</p>
<h3>Un roman a-t-il besoin d’un iconographe ?</h3>
<p>Rarement pour l’intérieur. Oui dès qu’il y a cahier photo, archives familiales à sécuriser, ou couverture dont la source n’est pas l’illustrateur. Sinon, orientez-vous vers illustration ou photo de commande.</p>

