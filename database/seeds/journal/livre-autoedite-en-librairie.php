<h2>Combien d’exemplaires déposer&nbsp;?</h2>
<p>Cinq, c’est un essai. Quinze, c’est déjà une confiance, ou un auteur très local. Au-delà, vous transformez le libraire en stockeur. Mieux vaut un réassort de 5 après deux semaines de rotation qu’un carton de 40 «&nbsp;pour qu’il ne manque pas&nbsp;».</p>
<p>Adaptez au lieu. Un roman généraliste se perd dans les bacs&nbsp;; un ouvrage ancré (ville, métier) se vend mieux près de son sujet. Proposez le dépôt où le lecteur existe.</p>
