<h2>Questions fréquentes</h2>
<h3>Un libraire peut-il refuser un autoédité&nbsp;?</h3>
<p>Oui, et c’est fréquent. Manque de place, hors assortiment, livre pas prêt, déjà trop d’auteurs locaux. Un refus n’est pas un jugement sur le roman&nbsp;; un «&nbsp;revenez avec l’ISBN et cinq ex.&nbsp;» en est un, utile.</p>
<h3>Faut-il un diffuseur pour entrer en librairie&nbsp;?</h3>
<p>Non pour un dépôt de proximité. Oui si vous visez un réseau national et des commandes Dilicom fluides. Le diffuseur est un métier, avec des seuils et des retours, pas un tampon que l’on achète au chapitre 1.</p>
<h3>La remise 30–40&nbsp;% s’applique-t-elle aussi en grand compte&nbsp;?</h3>
<p>Les réseaux et les enseignes ont leurs grilles, souvent plus dures, et leurs centrales. Cet article parle de l’indépendant en dépôt. Ne copiez pas une remise de grand compte sur une petite boutique, ni l’inverse.</p>
<h3>Combien de librairies viser pour un premier roman&nbsp;?</h3>
<p>Plutôt cinq bien suivies que trente abandonnées. Le temps de tournée, de facture et de reprise est un vrai poste. Ajoutez-y les salons si le livre a un public présent.</p>
<h3>Le dépôt légal remplace-t-il le démarchage&nbsp;?</h3>
<p>Non. La BnF archive. Elle ne place pas le livre en rayon. Le démarchage, lui, est une conversation avec quelqu’un qui a une table et une caisse.</p>

