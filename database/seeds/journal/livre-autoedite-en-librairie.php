<h2>Dépôt, office, compte ferme&nbsp;: trois circuits</h2>
<p>Le <strong>dépôt-vente</strong> est le chemin le plus fréquent pour un autoédité. Vous laissez 5 à 15 exemplaires. Le libraire paie ce qu’il vend, selon un rythme convenu (mensuel, trimestriel), et vous reprend l’invendu — ou vous le récupérez vous-même. Il n’y a pas de promesse de table, seulement une présence possible.</p>
<p>L’<strong>office</strong>, dans le circuit professionnel, est un envoi décidé par un diffuseur vers un réseau. Les libraires reçoivent, peuvent retourner, travaillent à la remise habituelle du réseau. Sans diffuseur, vous n’êtes pas «&nbsp;à l’office&nbsp;». Dire le contraire à un libraire, c’est perdre sa confiance dès la première phrase.</p>
<p>Le <strong>compte ferme</strong> est un achat&nbsp;: le libraire paie les volumes, les retours sont limités ou nuls. C’est rare pour un inconnu, plus fréquent après deux rotations, pour un auteur local attendu, ou pour un ouvrage très ciblé (histoire de la ville, guide). Ne le exigez pas au premier rendez-vous.</p>

<h2>Quelle remise accorder au libraire&nbsp;?</h2>
<p>La fourchette utile en 2026 pour un dépôt d’autoédité est <strong>30 à 40&nbsp;%</strong> du prix public TTC. En dessous de 30&nbsp;%, beaucoup d’indépendants refusent&nbsp;: la remise doit couvrir la place, le personnel et le risque d’invendu. Au-dessus de 40&nbsp;%, c’est vous qui travaillez à perte si la fabrication est déjà haute.</p>
