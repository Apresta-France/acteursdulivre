<h2>ISBN, Dilicom, diffuseur&nbsp;: ce qui manque souvent</h2>
<p>Sans ISBN, beaucoup de librairies ne peuvent pas fiches le livre, ni le commander, ni le rentrer en caisse. Le code-barres sur la quatrième n’est pas un gadget. Le dépôt légal (BnF) est une obligation dès que l’ouvrage circule&nbsp;; ce n’est pas un sésame commercial, mais son absence signale l’amateur.</p>
<p>Dilicom et les bases professionnelles sont le langage des commandes. Un autoédité sans diffuseur n’y est pas automatiquement. Certains intermédiaires proposent une entrée de fiche&nbsp;; d’autres libraires rentrent le titre à la main. Demandez ce que <em>cette</em> librairie sait faire, au lieu d’affirmer que vous êtes «&nbsp;distribué&nbsp;».</p>
<p>Un diffuseur-distributeur (les grands noms du circuit) s’adresse aux <a href="/metiers/edition">maisons</a> qui ont un programme, des retours, une logistique. Ce n’est pas le premier achat d’un roman unique. Viser l’office national avant d’avoir dix dépôts locaux qui tournent, c’est inverser la preuve.</p>

<h2>Comment aborder une librairie indépendante&nbsp;?</h2>
<p>Passez, à un horaire calme, avec un exemplaire fini — pas un PDF sur téléphone. Présentez-vous en une phrase (titre, genre, lien local s’il existe). Proposez le dépôt et la remise, pas «&nbsp;un partenariat win-win&nbsp;». Laissez une feuille avec contact, ISBN, prix, remise, et la possibilité de reprise.</p>
