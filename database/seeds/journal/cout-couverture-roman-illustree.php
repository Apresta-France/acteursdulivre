<h2>Questions fréquentes</h2>
<h3>Peut-on faire une couverture à moins de 250 € ?</h3>
<p>Oui, en amateur, en template, ou en échange. Le risque n’est pas moral, il est commercial : lisibilité, dos faux, droits d’une image mal sourcée. À 120 €, demandez ce qui est exclu.</p>
<h3>Faut-il la même couverture en poche et en grand format ?</h3>
<p>Souvent une adaptation, pas un copier-coller. Le format change, le dos aussi, parfois le titre. Prévoyez une ligne « déclinaison format » plutôt qu’une nouvelle illustration.</p>
<h3>Qui choisit entre deux pistes, l’auteur ou le graphiste ?</h3>
<p>L’auteur décide ; le graphiste argumente. Si vous votez en famille sur six visuels, vous n’achetez plus une direction, vous diluez. Une règle : une piste retenue, une liste de retouches bornée (deux allers-retours).</p>
<h3>La 4e de couverture est-elle incluse ?</h3>
<p>Elle doit l’être dans un devis de couverture livre. Vérifiez : texte, ISBN, prix, mentions légales, bio courte. La rédaction de la 4e est un autre métier (édition, presse) si elle n’existe pas encore.</p>
<h3>Peut-on réutiliser l’illustration pour une série ?</h3>
<p>Seulement si la cession le dit. Une collection visuelle se négocie dès le tome 1, ou se paie à chaque volume. Ne le déduisez pas du silence du devis.</p>

