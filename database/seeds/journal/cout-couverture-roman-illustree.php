<h2>Quelles déclinaisons prévoir dès le brief ?</h2>
<p>Le fichier imprimeur (fond perdu, dos au grammage réel, pelliculage). La vignette librairie en ligne (lisible à 120 pixels de haut). La version e-pub. Parfois un bandeau, un visuel <a href="/metiers/presse-com">service de presse</a>, une affiche de salon. Chacune peut être une ligne de 40 à 80 € — ou un malentendu à 400 € si l’on « ajuste » sans brief.</p>
<p>Le dos dépend du papier et du tirage. Une couverture livrée avant le devis <a href="/metiers/impression">imprimeur</a> devra être recalée. Prévoyez ce calage, ou attendez le grammage. L’article <a href="/journal/choisir-papier-bouffant-offset-recycle">Choisir son papier</a> explique pourquoi la main du livre change le dos.</p>

<h2>Comment briefer sans tuer la piste ?</h2>
<p>Genre, promesse, titres comparables (trois, pas trente), contraintes (collection, mention de prix, bandeau), ce qui est interdit (visages trop réels, symboles, IA). Donnez le texte de 4e <em>déjà corrigé</em> : une 4e fautée se voit plus que le chapitre 3. Joignez le format (135 × 210, poche, etc.) et le nombre de pages estimé.</p>
<p>Deux ou trois pistes, puis une finale, est un standard honnête. Six pistes « pour voir » : vous achetez une direction artistique, pas une couverture. Cela se tarife autrement.</p>

<h2>Quels droits figer pour 300 à 900 € ?</h2>
<p>Durée, territoires, supports, exclusivité, réédition. C’est le sujet de l’article <a href="/journal/cession-droits-illustration">Cession de droits en illustration</a>. En une phrase : 300 à 900 € achètent en général le livre identifié, pas le merchandising mondial. Un conseil <a href="/metiers/juridique">juridique</a> vaut dès que l’usage sort de la jaquette.</p>
