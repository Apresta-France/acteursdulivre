<h2>Pourquoi le forfait « couverture comprise » piège-t-il ?</h2>
<p>Parce qu’il noie l’image dans la maquette, et la cession dans l’image. Vous ne savez plus si 400 € paient une composition sur une photo libre de droits, ou une illustration originale cédée pour trois ans en France. À la réédition poche, la surprise arrive.</p>
<blockquote>
