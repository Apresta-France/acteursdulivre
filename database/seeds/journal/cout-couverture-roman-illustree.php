<h2>Qu’achète-t-on sous le mot « couverture » ?</h2>
<p>Trois objets se cachent sous le même mot. Un <em>graphisme de couverture</em> : choix typographiques, hiérarchie titre / auteur, 4e, dos calculé. Une <em>image</em> : illustration, photo, collage. Une <em>cession</em> : le droit d’exploiter cette image. Un devis qui n’en nomme qu’un des trois n’est pas un devis de couverture, c’est une ligne de catalogue.</p>
<p>Le <a href="/metiers/maquette">maquettiste livre</a> et l’<a href="/metiers/illustration">illustrateur</a> ne sont pas interchangeables. Un graphiste « qui fait aussi la couverture » peut exceller en typo et sous-traiter l’image — ou l’inverse. Demandez qui signe quoi, et des références <em>imprimées</em>, pas seulement des mockups écran.</p>

<h2>Typographie seule ou illustration originale ?</h2>
<p>Une typo soignée suffit à beaucoup de romans contemporains, d’essais, de recueils. Elle coûte moins cher, se décline plus vite, et évite les conflits de droits. Elle demande un vrai métier : un caractère mal choisi, un titre illisible à deux mètres en <a href="/metiers/librairie">librairie</a>, et le livre disparaît dans le rayon.</p>
<p>L’illustration originale s’impose quand le genre la promet (fantasy, jeunesse, certains polars) ou quand l’auteur a déjà une image mentale non négociable. Elle ajoute 300 à 900 €, parfois plus, et un délai de recherche + croquis + finale. Elle n’ajoute de la valeur que si la cession suit.</p>
