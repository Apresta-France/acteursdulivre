<h2>Comment passer des pages au temps d’écoute&nbsp;?</h2>
<p>Une page de roman n’est pas une minute. Tout dépend du format, du corps et de la quantité de dialogue. Un 300 pages poche a souvent moins de mots qu’un 300 pages grand format aéré. D’où la fourchette <strong>8 à 14 heures</strong> plutôt qu’un chiffre unique.</p>
