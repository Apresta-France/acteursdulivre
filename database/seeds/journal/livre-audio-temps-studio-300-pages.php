<h2>Que facturent vraiment les narrateurs&nbsp;?</h2>
<p>La fourchette <strong>1&nbsp;200 à 3&nbsp;500&nbsp;€</strong> pour 300 pages couvre, sur le marché français 2026, une narration humaine de roman — auteur qui lit le sien, ou comédien — dans une qualité «&nbsp;plateforme&nbsp;», hors grande vedette. Le bas de fourchette suppose souvent une voix moins expérimentée, un rythme serré, peu de personnages. Le haut suppose une direction, des voix distinctes, un texte difficile.</p>
<p>D’autres unités circulent&nbsp;: tarif à l’heure finie, à l’heure de cabine, au feuillet lu, au forfait livre. Convertissez comme pour un devis de traduction. Une heure finie à 180&nbsp;€ sur 10 heures, c’est 1&nbsp;800&nbsp;€ — dans la fourchette. Une heure de cabine à 80&nbsp;€ sur 40 heures de présence, c’est 3&nbsp;200&nbsp;€ — encore dedans, mais ce n’est plus le même objet.</p>
