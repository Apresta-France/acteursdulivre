<h2>Questions fréquentes</h2>
<h3>300 pages, c’est toujours 10 heures d’audio&nbsp;?</h3>
<p>Non. La fourchette utile est 8 à 14 heures. Un manuscrit aéré, très dialogué ou en grand format sort du milieu. Le seul chiffre fiable est le décompte de mots sur le fichier gelé.</p>
<h3>L’auteur peut-il se narrer lui-même&nbsp;?</h3>
<p>Oui, si la voix tient 8 à 14 heures et si un professionnel prend le son. L’auteur-lecteur est un choix artistique, pas une économie automatique&nbsp;: le studio et le master restent.</p>
<h3>Le ratio 3–5× inclut-il le montage&nbsp;?</h3>
<p>Il décrit surtout le temps de prise. Le montage est un autre multiple, souvent 1 à 2 fois la durée d’écoute. Un devis «&nbsp;studio&nbsp;» doit dire s’il parle de cabine, de montage, ou des deux.</p>
<h3>Faut-il une musique d’habillage&nbsp;?</h3>
<p>Ce n’est pas obligatoire. Beaucoup de romans circulent à voix nue. Si vous en mettez une, négociez les droits du morceau. Un habillage mal choisi date le livre plus vite que la voix.</p>
<h3>Quand payer le narrateur&nbsp;?</h3>
<p>Souvent un acompte à la réservation de cabine, le solde à la livraison du master validé. Le chapitre pilote peut être une première jalon. Le paiement de la mission, sur la plateforme, reste hors site.</p>

