<h2>Préparation, direction, mastering&nbsp;: les postes oubliés</h2>
<p>Avant d’allumer le micro, le narrateur lit, annote les noms, décide des voix, coupe les phrases impossibles à dire. Cette préparation prend un à trois jours sur 300 pages. Si elle n’apparaît pas, elle est dans le forfait — ou elle n’existe pas, et on l’entend.</p>
<p>La <strong>direction artistique</strong> (un tiers qui écoute et recadre) est rare en autoédition, précieuse dès que le texte a plusieurs niveaux de langue. Elle se facture à la séance. Le <strong>mastering</strong> aligne le volume, retire les bruits, découpe les pistes par chapitre — exigence des distributeurs. Ce n’est pas «&nbsp;exporter le wav&nbsp;».</p>
<p>Musique d’habillage, générique, extraits lus pour la <a href="/metiers/presse-com">presse</a>&nbsp;: lignes à part, et droits à part (compositeur, interprète). Un piano libre de droits mal mixé dessert plus qu’un silence propre.</p>

<h2>Comment briefer une voix pour un roman&nbsp;?</h2>
<p>Envoyez le PDF paginé définitif, ou une version clairement gelée. Indiquez le genre, l’âge des voix, ce qui ne se négocie pas (un accent, un nom). Signalez les passages à ne pas «&nbsp;jouer&nbsp;» (documents, listes, poèmes).</p>
<p>Fournissez une page de prononciation&nbsp;: toponymes, personnages, mots étrangers. Un retour après trois heures de rush coûte plus cher qu’une liste envoyée le lundi. Si l’auteur lit lui-même, prévoyez un coach ou un ingénieur&nbsp;: l’auteur sait le texte, pas forcément le micro.</p>
<p>Écoutez un extrait déjà en ligne, sur un roman comparable, pas une démo de pub. Les <a href="/prestations">prestations</a> audio à prix affiché doivent dire si le montage est inclus. Les <a href="/prestataires">prestataires</a> de l’annuaire précisent cabine maison ou studio extérieur.</p>

<h2>Quel studio pour un premier livre audio&nbsp;?</h2>
<p>Une cabine traitée et un preneur de son valent mieux qu’un départ de placard, même avec un micro cher. Le souffle, la pièce, la bouche trop près&nbsp;: l’auditeur rend le fichier avant la fin du chapitre 1. Pour un premier livre, un studio à la journée plus un narrateur qui a déjà livré des masters «&nbsp;plateforme&nbsp;» est le schéma le plus sûr.</p>
<p>Enregistrez un chapitre pilote, validez le ton, puis enchaînez. Revenir sur 10 heures pour changer la voix du père est un gouffre. C’est la même logique que le bon à tirer en <a href="/metiers/impression">impression</a>&nbsp;: on fige avant la série.</p>
