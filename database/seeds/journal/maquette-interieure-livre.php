<h2>Pourquoi les marges et la justification ne sont pas décoratives ?</h2>
<p>Des marges trop justes fatiguent, empêchent de tenir le livre, et se font manger par le brochage. Une justification trop large crée des rivières ; trop étroite, des césures en cascade. Le corps 11 sur 13 n’est pas un dogme, mais un roman en 9 points « pour gagner des pages » se lit comme un contrat.</p>
<p>Le maquettiste règle aussi les veuves, les orphelines, les lignes de trop en bas de page, les blancs de chapitre. C’est un travail invisible quand il est fait, criant quand il ne l’est pas. C’est lui, plus que le pelliculage, qui sépare un livre d’un dossier relié.</p>

<h2>Faut-il maquetter avant ou après la correction ?</h2>
<p>Après. La <a href="/metiers/correction">correction</a> d’un roman de 520 000 signes (620 à 1 100 €) doit précéder la mise en pages. Corriger sur épreuves, oui : une passe courte pour les fautes introduites et les coupures. Corriger le roman entier après maquette, non : chaque suppression recale vingt pages.</p>
<p>La préparation de copie (1 200 à 2 400 €) et la <a href="/metiers/beta-lecture">bêta-lecture</a> (180 à 450 €) sont encore plus en amont. L’ordre utile est décrit dans <a href="/journal/preparation-copie-ou-correction">Préparation de copie ou correction</a> et dans le <a href="/journal/cout-fabrication-roman-autoedition">budget de fabrication</a>.</p>

<h2>Comment le dos et le papier commandent-ils la couverture ?</h2>
<p>Le dos dépend du nombre de pages et de l’épaisseur de la feuille. Choisir le papier (bouffant 80 g, 90 g, recyclé) avant la finale de couverture évite un second BAT. L’impact papier sur le devis impression se situe souvent entre 10 et 25 %. Voir <a href="/journal/choisir-papier-bouffant-offset-recycle">Choisir son papier</a>.</p>
<p>Une <a href="/metiers/illustration">illustration</a> de couverture se calcule avec les fonds perdus et la zone de titraille, pas comme une image Instagram. Les droits (durée, territoires, supports) se figent à part : <a href="/journal/cession-droits-illustration">cinq lignes de cession</a>.</p>

<h2>Qu’exiger comme références et comme brief ?</h2>
<p>Des livres imprimés, du même format si possible. Un PDF écran ment sur le gris, le corps, les marges. Brief : format, nombre de signes, genre, modèle de collection (trois titres), contraintes (collection, mentions), papier pressenti, imprimeur pressenti, délai réel. Fichier : une version corrigée, styles de titres déjà propres si possible.</p>
<p>Pour un essai avec notes ou un ouvrage illustré, le devis sort de la fourchette 700-1 400 €. L’<a href="/metiers/iconographie">iconographe</a> et le maquettiste doivent se parler avant la première planche. Un <a href="/metiers/edition">éditeur</a> freelance peut piloter cette coordination si vous n’avez pas le temps.</p>

<h2>Comment comparer deux devis de maquette ?</h2>
<p>Même format, même volume, même liste (intérieur, couverture, épreuves, sources, e-pub). Même nombre d’allers-retours. Un « pour vendredi » se paie. Un gabarit réutilisable pour une collection aussi — c’est une plus-value, pas un dû gratuit.</p>
