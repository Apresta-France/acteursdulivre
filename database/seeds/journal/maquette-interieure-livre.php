<h2>Questions fréquentes</h2>
<h3>Peut-on maquetter soi-même dans un traitement de texte ?</h3>
<p>On peut produire un intérieur lisible pour un cercle restreint. Dès qu’il y a un imprimeur, un dos, un ISBN et une librairie, les limites apparaissent : césures, fonds, profils, page de titre. Le coût d’une reprise professionnelle dépasse souvent l’économie initiale.</p>
<h3>L’e-pub est-il offert avec la maquette papier ?</h3>
<p>Rarement. Ce sont deux fabrications. Un export automatique depuis l’InDesign n’est pas un e-pub soigné (notes, images, table). Prévoyez une ligne, ou un prestataire dédié.</p>
<h3>Combien de BAT faut-il ?</h3>
<p>Un BAT écran pour le texte et la grille, un BAT papier chez l’imprimeur pour la couleur et le pelliculé. La maquette intérieure se juge aussi imprimée : les gris, le corps, les marges mentent à l’écran.</p>
<h3>Qui corrige les épreuves, le maquettiste ou le correcteur ?</h3>
<p>Le correcteur relit le texte sur épreuves. Le maquettiste corrige les accidents de composition (folios, titres, décalages). Les deux métiers se parlent ; ils ne se remplacent pas.</p>
<h3>Faut-il livrer les polices avec le PDF ?</h3>
<p>Les polices doivent être enrobées ou converties selon le cahier de l’imprimeur. Livrer les fichiers de polices à l’auteur est une question de licence, pas un geste anodin. Le PDF/X bien fait évite souvent de circuler les fontes.</p>

