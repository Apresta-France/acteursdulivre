<h2>Quand ce n’est pas (encore) obligatoire</h2>
<p>Un manuscrit circulant entre amis, un tirage familial non vendu, un fichier que vous n’offrez pas au public : ce n’est pas une mise en circulation. Dès que vous vendez, déposez en librairie, exposez en salon ou mettez en vente en ligne, le régime change. L’entre-deux (« je vends seulement à mes lecteurs Instagram ») est déjà une mise à disposition.</p>
