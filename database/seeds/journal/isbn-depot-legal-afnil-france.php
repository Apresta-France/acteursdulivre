<h2>Questions fréquentes</h2>
<h3>Peut-on vendre un livre sans ISBN ?</h3>
<p>Oui sur une table, de la main à la main, ou en salon très local. En librairie et sur la plupart des boutiques en ligne, c’est impraticable. Le dépôt légal, lui, ne disparaît pas faute d’ISBN si le livre circule.</p>
<h3>Le dépôt légal protège-t-il le droit d’auteur ?</h3>
<p>Non. En France, le droit naît de la création, sans dépôt constitutif. Le dépôt légal documente l’existence de l’édition. La preuve d’antériorité se construit autrement (constat, horodatage, envoi à soi-même n’est plus le réflexe utile). Un juriste cadre si besoin.</p>
<h3>Faut-il devenir éditeur AFNIL pour un seul livre ?</h3>
<p>Pas nécessairement. Beaucoup d’autoédités passent par un intermédiaire (0 à 50 €). Devenir éditeur a un sens si vous enchaînez les titres et voulez maîtriser la notice. Ce n’est pas un sésame de prestige.</p>
<h3>Combien d’exemplaires envoyer à la BnF ?</h3>
<p>Suivez la notice BnF du moment pour votre type de document (imprimé, nombre d’exemplaires éditeur). Ne copiez pas un chiffre lu sur un forum de 2014. Ajoutez le port à votre budget, pas au « gratuit » du service.</p>
<h3>L’imprimeur peut-il s’occuper de tout ?</h3>
<p>Certains ateliers accompagnent le dépôt imprimeur. Le dépôt éditeur reste souvent le vôtre. Faites écrire qui envoie quoi, et gardez une copie du bordereau.</p>

