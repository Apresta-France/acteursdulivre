<h2>Dépôt légal : gratuit, mais pas virtuel</h2>
<p>Le dépôt légal relève du Code du patrimoine. Il vise la conservation et le recensement, pas la promotion. Dès que l’ouvrage est mis à disposition du public en France, l’éditeur — et, selon les cas, l’imprimeur — doit déposer. Pour un autoédité qui publie sous son nom, <em>vous</em> êtes souvent cet éditeur au sens du dépôt, même sans maison.</p>
<p>La procédure BnF (formulaire, exemplaires, mentions) évolue dans le détail : suivez la notice en vigueur au moment de l’envoi. Le service est gratuit ; le carton, l’affranchissement et le temps de colisage ne le sont pas. Prévoyez ces exemplaires <em>en plus</em> du tirage librairie et du service de presse, pas en les prélevant sur les 5 à 15 livres d’un dépôt.</p>
