<p>L’ISBN identifie une édition précise (titre, format, éditeur mentionné). Il sert aux libraires, aux distributeurs, aux bases Dilicom, aux sites de vente. Sans lui, le dépôt en <a href="/metiers/librairie">librairie</a> et beaucoup de commandes en ligne deviennent artisanaux. Le code-barres EAN sur la couverture reprend cet ISBN : c’est le travail du <a href="/metiers/maquette">maquettiste</a> et de l’<a href="/metiers/impression">imprimeur</a>, pas une décoration.</p>
