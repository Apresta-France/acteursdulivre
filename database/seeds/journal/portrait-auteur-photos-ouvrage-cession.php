<h2>Photos d’ouvrage : 4e, site, librairie</h2>
<p>Une bonne photo d’ouvrage sert la <a href="/metiers/librairie">librairie</a> (commande, événement), le site, les fiches de vente en ligne, et le dossier. Elle n’est pas une capture d’écran de la couverture en JPEG aplati. Elle montre l’objet : papier, dos, main, lumière. Les libraires et les journalistes la reconnaissent en une seconde.</p>
<p>Usages à lister : fiche livre, e-commerce, 4e (si la photo y figure), réseaux, communiqué, éventuelle affiche de rencontre. Si une <a href="/metiers/reliure">reliure</a> ou un façonnage particulier est le sujet, dites-le : le photographe cadré autrement.</p>
<p>Pour un album ou un livre illustré, l’<a href="/metiers/iconographie">iconographe</a> intervient sur les images <em>intérieures</em> (recherche, légendes, droits). Ce n’est pas le même devis que « photographier le livre fermé sur une table ».</p>

<h2>Les cinq lignes du contrat de cession</h2>
<p>Le Code de la propriété intellectuelle exige que la cession des droits d’exploitation soit <strong>écrite</strong> et précise. En pratique, cinq lignes évitent le rachat :</p>
<ol>
  <li><strong>Droits</strong> — reproduction, représentation ; parfois adaptation (recadrage, noir et blanc, détail).</li>
  <li><strong>Supports</strong> — print, web, réseaux, presse, publicité : une liste, pas « etc. ».</li>
  <li><strong>Territoires et langues</strong> — France, francophonie, monde ; durée.</li>
  <li><strong>Exclusivité</strong> — oui / non, et jusqu’à quand ; ce que le photographe peut montrer à son book.</li>
  <li><strong>Prix et ce qui est hors champ</strong> — nouvelle séance, nouveaux usages, réédition au-delà de X années.</li>
</ol>
<blockquote>
  <p>« “Tous supports” n’est pas une cession. C’est une invitation à se revoir devant un juriste. »</p>
</blockquote>
