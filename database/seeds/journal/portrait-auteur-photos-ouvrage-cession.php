<h2>Trois objets, trois logiques de droits</h2>
<p>Le <strong>portrait</strong> représente une personne. Outre le droit d’auteur du photographe, le droit à l’image de l’auteur (ou du modèle) doit être autorisé. En pratique, si vous êtes à la fois commanditaire et sujet, la séance le règle — à condition que le contrat dise qui peut publier, et où.</p>
<p>La <strong>photo d’ouvrage</strong> représente un livre : couverture, tranche, ouverture, empilement. Le photographe détient les droits sur <em>sa</em> photo. La couverture elle-même appartient à l’<a href="/metiers/illustration">illustrateur</a> ou au graphiste, selon la cession déjà signée. Photographier le livre pour le vendre n’étend pas automatiquement les droits de l’illustration aux affiches et aux ads.</p>
<p>Le <strong>reportage</strong> (salon, dédicace, atelier) mélange visages, lieux, parfois des mineurs. C’est un autre brief : autorisations de lieu, personnes identifiables, usages presse. Ne le glissez pas dans « et quelques photos le jour J » au tarif du portrait studio.</p>

<h2>Portrait : usages courants d’un auteur</h2>
<p>La liste minimale, pour un auteur qui publie en 2026, tient en cinq lignes. Site personnel et page éditeur ; quatrième de couverture et rabat ; dossier de presse et <a href="/metiers/presse-com">service de presse</a> ; réseaux de l’auteur et de la maison ; biographies (salons, dossiers de subvention). Si vous visez l’étranger, ajoutez territoires et langues.</p>
<p>Ce qui n’est <em>pas</em> dans la liste minimale : l’achat d’espace publicitaire, les campagnes d’influence rémunérées, l’affichage, les goodies, la cession à un tiers (journal, site de vente) pour un usage commercial autonome. Chaque ajout se chiffre. Un portrait à 250 € « tous supports, tous territoires, durée des droits » est soit une faveur, soit un contrat que le photographe n’a pas lu.</p>
