<h2>Comment ne pas racheter deux fois</h2>
<p>Écrivez la liste d’usages <em>avant</em> la séance, pas après, quand le visuel est déjà sur le site. Joignez-la au devis. Si la maison d’<a href="/metiers/edition">édition</a> arrive plus tard, elle devra soit entrer dans cette cession, soit négocier une extension — mieux vaut l’avoir prévu (« cession transférable à l’éditeur du titre »).</p>
<p>Archivez les fichiers avec le contrat (date, nom du photographe, usages). Dans deux ans, personne ne se souviendra si Instagram était inclus. Les <a href="/prestations">prestations</a> photo sérieuses l’écrivent ; les <a href="/prestataires">prestataires</a> de l’annuaire aussi, en principe.</p>
<p>Si vous réutilisez une photo d’un proche « qui photographie bien », le droit d’auteur existe quand même. Un accord écrit court vaut mieux qu’une brouille familiale le jour de la 4e.</p>
<p>L’<a href="/inscription">inscription</a> est gratuite. Un brief photo utile cite le format du livre, les usages, la date de parution et le lieu de séance. La page <a href="/confiance">Confiance</a> rappelle le cadre du travail humain : pas d’image générée à la place d’une prise de vue.</p>

<h2>Questions fréquentes</h2>
<h3>Qui possède le portrait : l’auteur ou le photographe ?</h3>
<p>Le photographe reste titulaire du droit d’auteur. L’auteur (sujet / commanditaire) reçoit une cession d’usages. Sans contrat, chacun croit posséder ce que l’autre n’a pas vendu.</p>
<h3>Puis-je recadrer, filtrer, mettre en noir et blanc ?</h3>
<p>Seulement si la cession l’autorise (adaptation, modification). Un recadrage web courant est souvent accepté. Un filtre qui dénature, ou un détourage publicitaire, peut exiger un accord. Demandez-le une fois, par écrit.</p>
<h3>La mention du photographe est-elle obligatoire ?</h3>
<p>Le droit moral inclut la paternité. En pratique, on la place en 4e, en crédits site et en dossier de presse. Sur un avatar de 80 pixels, on convient parfois d’une mention en bio. Cela s’écrit, cela ne s’oublie pas.</p>
<h3>Faut-il une séance séparée pour l’ouvrage ?</h3>
<p>Pas toujours. Beaucoup de photographes livrent portrait et objet-livre dans la même demi-journée, si le brief le dit. Un reportage en librairie ou un packshot e-commerce soigné peuvent justifier une autre date.</p>
<h3>Et les photos prises par l’éditeur le jour de la signature ?</h3>
<p>Elles ont un auteur (souvent un salarié ou un pigiste) et des usages (souvent internes ou presse). Ne les supposez pas libres pour votre site personnel ou vos ads. Demandez la cession ou refaites une séance.</p>

